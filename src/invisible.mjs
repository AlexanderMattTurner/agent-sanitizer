const isKeycapBase = memoizedCpPredicate(KEYCAP_BASE);
// U+FE0F (VS16) forces emoji presentation, U+FE0E (VS15) forces text
// presentation (☺︎ vs ☺); either one directly after a pictograph is part of a
// visible glyph, not a hidden variation-selector run.
const PRESENTATION_SELECTORS = new Set([0xfe0e, 0xfe0f]);

// ─── Emoji tag sequences (subregional flags) ─────────────────────────────────
// A subregional flag (🏴󠁧󠁢󠁳󠁣󠁴󠁿 Scotland, 🏴󠁧󠁢󠁷󠁬󠁳󠁿 Wales, 🏴󠁧󠁢󠁥󠁮󠁧󠁿 England …) is a WAVING
// BLACK FLAG tag_base (U+1F3F4, a visible pictograph) followed by one or more
// tag characters in U+E0020–U+E007E, terminated by U+E007F CANCEL TAG. Only that
// exact grammar is preserved verbatim; any tag char (the whole U+E0000–U+E007F
// block is category Cf) NOT inside a well-formed 🏴 … CANCEL run stays stripped —
// tag chars are the top ASCII-smuggling vector, so preservation fails CLOSED on a
// malformed/partial run.
const TAG_BASE = 0x1f3f4; // WAVING BLACK FLAG
const TAG_CANCEL = 0xe007f; // CANCEL TAG (the required terminator)
const TAG_SPEC_MIN = 0xe0020; // first tag char a flag sequence may carry
const TAG_SPEC_MAX = 0xe007e; // last tag char a flag sequence may carry
// A tag char decodes to ASCII (cp − 0xE0000), so a grammatically-valid
// 🏴 … CANCEL run can spell ARBITRARY ASCII ("ignore rules") and, if preserved
// only on grammar, smuggle it verbatim to the model. Preservation is therefore
// gated on the decoded payload naming a REGISTERED subdivision (the only tag
// sequences that render as a real flag) and on a tag-char cap — every other
// run, however well-formed, stays stripped (fail closed on the top ASCII vector).
const REGISTERED_TAG_PAYLOADS = new Set(["gbeng", "gbsct", "gbwls"]);
// Longest registered subdivision payload is 5 tag chars; cap a touch above it so
// a malformed-but-registered-prefix run can never carry a long ASCII rider.
const MAX_TAG_SPEC_CHARS = 6;

// ─── Registered emoji glyphs ──────────────────────────────────────────────────
// Some preserved invisibles are not a choice the author made beside a glyph but
// part of the glyph's spelling: the tag characters of an RGI subdivision flag,
// the VS16 that gives a text-default emoji (Emoji but not Emoji_Presentation:
// ⚠ ✔ 🏳 ❤ and the keycap digits) its emoji form, and a ZWJ between two
// pictographs (👨‍👩‍👧, 🏳️‍🌈). They are KIND_GLYPH, preserved whenever the
// carve-out is on and charged to no budget: charging them made a README with
// ten Scotland flags, or fifty ⚠️ lines, read as a covert channel the moment its
// glyphs outran a cover allowance sized for the joiners and selectors that DO
// hide a bit apiece. A VS16 after an Emoji_Presentation=Yes base (😀️) changes
// nothing that renders and keeps its budget, as does VS15, whose text form is
// the default it asks for.
//
// The ZWJ rule is UAX #29's GB11, not the RGI list, so a ZWJ between two
// pictographs Unicode never registered (😀‍😀) is exempt too. It renders as two
// glyphs either way, so it hides one bit, present or absent, per pair of
// adjacent pictographs: the accepted residual.
const VS16 = 0xfe0f;

/** True when `cp` is Emoji but not Emoji_Presentation (see above).
 * @param {number} cp @returns {boolean} */
function isTextDefaultEmoji(cp) {
  if (cp >= CP_PROPS_END) return inSpans(EMOJI_TEXT_DEFAULT, cp);
  return (cpProps(cp) & PROP_EMOJI_TEXT_DEFAULT) !== 0;
}

/** True when `cp` is an Emoji_Modifier (a skin tone); -1 is not.
 * @param {number} cp @returns {boolean} */
function isEmojiModifierCp(cp) {
  if (cp < 0) return false;
  if (cp >= CP_PROPS_END) return inSpans(EMOJI_MODIFIER, cp);
  return (cpProps(cp) & PROP_EMOJI_MODIFIER) !== 0;
}

/** True when `cp` is Extended_Pictographic; -1 is not.
 * @param {number} cp @returns {boolean} */
function isExtendedPictographic(cp) {
  if (cp < 0) return false;
  if (cp >= CP_PROPS_END) return inSpans(EXTENDED_PICTOGRAPHIC, cp);
  return (cpProps(cp) & PROP_EXTENDED_PICTOGRAPHIC) !== 0;
}

/**
 * Upgrade to KIND_GLYPH each preserved VS16 on a text-default emoji, and each
 * preserved ZWJ GB11 keeps inside one grapheme: `Extended_Pictographic Extend*
 * ZWJ × Extended_Pictographic`. Extend is read as the selectors and skin tones,
 * the only Extend a preserved emoji joiner can have on its left (leftNonSelector
 * steps over selectors alone, and isEmojiLeft takes a modifier). Each walk stops
 * at a ZWJ, which is not Extend, so the pass is linear. Tag characters are
 * marked as they are found.
 * @param {Int32Array} cps @param {Int32Array} invisible  ascending indices
 * @param {Uint8Array} kind  updated in place
 */
function markRegisteredGlyphs(cps, invisible, kind) {
  for (const i of invisible) {
    if (cps[i] === VS16) {
      if (kind[i] === KIND_EMOJIVS && i > 0 && isTextDefaultEmoji(cps[i - 1]))
        kind[i] = KIND_GLYPH;
      continue;
    }
    if (kind[i] !== KIND_JOINER || cps[i] !== ZWJ) continue;
    if (!isExtendedPictographic(i + 1 < cps.length ? cps[i + 1] : -1)) continue;
    let p = i - 1;
    while (
      p >= 0 &&
      (isVariationSelectorCp(cps[p]) || isEmojiModifierCp(cps[p]))
    )
      p--;
    if (p >= 0 && isExtendedPictographic(cps[p])) kind[i] = KIND_GLYPH;
  }
}

// ─── Ideographic variation selectors (VS17–VS256, U+E0100–U+E01EF) ────────────
// An ideographic variation sequence is a CJK ideograph followed by a selector in
// U+E0100–U+E01EF. Preserved ONLY when the immediately preceding code point is a
// CJK ideograph — the registry-faithful structural gate (IVS apply to ideographs
// and nothing else).
//
// Derived from Unicode's own data rather than hand-transcribed block spans: the
// Unified_Ideograph property IS the set of unified ideographs (URO + every
// extension), generated from the pinned UCD, so a new extension arrives with
// the next UCD refresh instead of waiting for someone to notice. A hand-written
// table went stale exactly this way — it stopped at Extension H and so denied
// the 4,298 Extension J ideographs (U+323B0–U+33479) a legitimate IVS base. The
// runtime's ICU is not consulted: on Node 22.22 (Unicode 16) it does not know
// Extension J either.
//
// Script=Han is deliberately NOT used: it also covers radicals (U+2E80–U+2EF3),
// Kangxi radicals, U+3005/U+3007 and the ideographic-description characters,
// none of which is an IVS base. Script_Extensions=Han is wider still (it reaches
// U+00B7 MIDDLE DOT and the CJK punctuation shared with Kana), so it would let a
// full stop anchor a variation selector.
//
// The two Compatibility Ideograph BLOCKS stay literal: they are not
// Unified_Ideograph, and a block is not a property. Block boundaries are
// immutable by Unicode's stability policy, so a literal span stays correct
// forever; the contract test in test/invisible-unicode-tables.test.mjs pins
// that every ASSIGNED code point inside them is a Script=Han letter.
const IVS_MIN = 0xe0100;
const IVS_MAX = 0xe01ef;
/** @type {ReadonlyArray<readonly [number, number]>} */
const CJK_COMPATIBILITY_IDEOGRAPH_BLOCKS = [
  [0xf900, 0xfaff],
  [0x2f800, 0x2fa1f],
];

/** True when `cp` is a CJK ideograph (the only base an ideographic variation
 * selector legitimately follows), by the two tables below. -1 (past a string
 * boundary) is not.
 * @param {number} cp @returns {boolean} */
const inCjkIdeographTables = (cp) =>
  inSpans(UNIFIED_IDEOGRAPH, cp) ||
  inSpans(CJK_COMPATIBILITY_IDEOGRAPH_BLOCKS, cp);

/** {@link inCjkIdeographTables}, read off the per-code-point table where it
 * reaches (see cpProps).
 * @param {number} cp @returns {boolean} */
function isCjkIdeograph(cp) {
  if (cp < 0 || cp >= CP_PROPS_END) return inCjkIdeographTables(cp);
  return (cpProps(cp) & PROP_CJK_IDEOGRAPH) !== 0;
}

// Brahmic consonants: the only base a virama does half-form/conjunct work on.
// A bare or base-less halant + ZWJ carries no rendering and is a smuggling
// channel, so the Indic joiner is preserved only over one of these.
//
// The spans are GENERATED from the UCD (Indic_Syllabic_Category=Consonant in
// every script that owns a virama) by scripts/gen-joining-type.mjs. ECMAScript
// exposes no \p{Indic_Syllabic_Category=…} escape, and \p{Script=Devanagari}
// is the wrong shape on its own (it also holds the independent vowels
// U+0904–U+0914, which a virama never attaches to). Re-exported as part of
// this module's published surface.
export { BRAHMIC_CONSONANT_RANGES } from "./joining-type.mjs";

/** True when the code point `cp` is a Brahmic consonant; -1 (past a string
 * boundary) is not. A thin sign-guard over ./joining-type.mjs's table lookup.
 * @param {number} cp @returns {boolean} */
function isBrahmicConsonantCp(cp) {
  if (cp < 0) return false;
  if (cp >= CP_PROPS_END) return isBrahmicConsonant(cp);
  return (cpProps(cp) & PROP_BRAHMIC_CONSONANT) !== 0;
}

// ─── Blank-filler carve-out (Braille / archaic Hangul) ───────────────────────
// U+2800 (BRAILLE PATTERN BLANK) and the Hangul fillers render blank, so a RUN
// of them is a hidden channel — but a lone one does real work in genuine Braille
// (the empty cell) or archaic-Korean text, where stripping it mangles content.
// Gate them like the joiner carve-out: preserve one only next to a real,
// script-appropriate visible neighbour (a non-blank Braille cell; a Hangul
// jamo/syllable). A run of fillers has only fillers for neighbours, so it fails
// the anchor and is stripped — the run-length gate falls out of the anchor. The
// zero-width Mn marks in BLANK_NON_CF (U+034F/17B4/17B5) have no such benign
// standalone use, so they are never preserved.
//
// Blank fillers are NOT charged against the joiner/selector preserve budget:
// that budget's density model is "~1 preserved invisible per 8 visible chars"
// (PRESERVED_JOINER_PER_VISIBLE), measured on Persian ZWNJ prose, with a fixed
// PRESERVE_HARD_CAP ceiling. Blanks are an order of magnitude denser in genuine
// text — U+2800 IS the word space of Unicode Braille, and a Hangul filler
// completes a defective syllable — so charging them there mangled real content:
// a 40-word Braille passage lost 14 of its 39 word spaces (words run together)
// and a 200-word one kept 64 of 199, with `found` reporting a strip on a
// perfectly legitimate document. They draw on the anchor-proportional allowance
// below instead (see TOTAL_PRESERVED_BLANK_BUDGET).
const BRAILLE_BLANK = 0x2800;
const HANGUL_FILLERS = new Set([0x115f, 0x1160, 0x3164, 0xffa0]);
// Code points that trigger the carve-out path for blank fillers (see
// needsCarveOut). Written as \u escapes: a raw blank-rendering byte in a regex
// literal is invisible to the eye and a correctness landmine for the next editor.
const GATED_BLANK_RE = new RegExp("[\\u115F\\u1160\\u2800\\u3164\\uFFA0]", "u");

// Script=Braille, from the pinned UCD (identical to Script_Extensions=Braille —
// no character is shared with another script).
/** @param {number} cp @returns {boolean} */
const isBrailleScript = (cp) => inSpans(SCRIPT_BRAILLE, cp);

/** A real (non-blank) Braille cell — the anchoring neighbour for a U+2800 blank.
 * @param {number} cp @returns {boolean} */
function isBrailleCell(cp) {
  return cp !== BRAILLE_BLANK && isBrailleScript(cp);
}

// Script=Hangul, from the pinned UCD. NOT Script_Extensions=Hangul: that set
// also holds the CJK punctuation Korean text shares with Chinese and Japanese
// (U+3001 IDEOGRAPHIC COMMA, U+30FB KATAKANA MIDDLE DOT, U+FF61–U+FF65 …), so
// a Japanese middle dot would anchor — and
// thereby preserve — a Hangul filler in text with no Hangul in it at all.
/** @param {number} cp @returns {boolean} */
const isHangulScript = (cp) => inSpans(SCRIPT_HANGUL, cp);

/** A Hangul jamo/syllable (NOT itself one of the fillers) — the anchoring
 * neighbour for a Hangul filler. @param {number} cp @returns {boolean} */
function isHangul(cp) {
  if (HANGUL_FILLERS.has(cp)) return false; // a filler cannot anchor another filler
  return isHangulScript(cp);
}

// The carve analysis runs once per code point of every prompt and every tool
// output, so its per-code-point state is held in TYPED arrays of small integer
// codes rather than arrays of category strings: `Uint8Array` costs one byte per
// code point with no pointer to trace, where a `(string|null)[]` costs a machine
// word per entry and hands the collector one more object graph to walk on every
// blocking hook call. These are the codes; CODE_CATEGORY projects them back onto
// the public CATEGORY strings at the boundary, so nothing outside this module
// sees them.
const CODE_VISIBLE = 0;
const CODE_CF = 1;
const CODE_VS = 2;
const CODE_BLANK = 3;

// Preserve kinds, in the same one-byte-per-code-point spirit. KIND_NONE is the
// zero value, so a freshly allocated `kind` array already reads "payload" —
// which is the fail-closed default this analysis wants.
const KIND_NONE = 0;
const KIND_JOINER = 1;
const KIND_EMOJIVS = 2;
// Part of an emoji glyph's spelling, so outside every budget (see
// markRegisteredGlyphs).
const KIND_GLYPH = 3;
const KIND_STDVS = 4;
const KIND_IVS = 5;
const KIND_BLANK = 6;

/** Small code -> CHECKS category, indexed by the CODE_* values above. In CHECKS
 * order, so a code point in two sets reports the category the regexes would
 * report first. @type {(string|null)[]} */
const CODE_CATEGORY = [
  null,
  CATEGORY.CF,
  CATEGORY.VARIATION_SELECTORS,
  CATEGORY.BLANK_FILLERS,
];

// code point -> CODE_* above, projected from the SAME three code-point sets the
// CHECKS regexes are built from, in CHECKS order. Every CHECKS class holds
// single code points under the `u` flag, so a lookup and a `.test` answer
// identically; test/invisible-fast-path.test.mjs pins that over the whole
// code-point space, because a code point dropped here is one the scatter gate
// stops counting.
/** @type {Map<number, number>} */
const TRACKED_INVISIBLE = new Map();
for (const [code, codepoints] of /** @type {[number, Iterable<number>][]} */ ([
  [CODE_CF, CF_CODEPOINTS],
  [CODE_VS, [...VS].map((ch) => ch.codePointAt(0))],
  [CODE_BLANK, [...BLANK_NON_CF].map((ch) => ch.codePointAt(0))],
]))
  for (const cp of codepoints)
    if (!TRACKED_INVISIBLE.has(cp)) TRACKED_INVISIBLE.set(cp, code);

// The same classes for the BMP and the SMP, by array index: every visible
// character of a CJK, Persian or Devanagari page asks, and so does every
// pictograph of an emoji page (the SMP), and a hash lookup per character is a
// measurable share of analysing either. 128 KB, CODE_VISIBLE (0) where unset.
const TRACKED_TABLE_END = 0x20000;
const TRACKED_LOW = new Uint8Array(TRACKED_TABLE_END);
for (const [cp, code] of TRACKED_INVISIBLE)
  if (cp < TRACKED_TABLE_END) TRACKED_LOW[cp] = code;

/**
 * The CODE_* class a code point belongs to, or CODE_VISIBLE when it is not
 * payload-capable (an ordinary visible character).
 * @param {number} cp
 * @returns {number}
 */
function classifyCp(cp) {
  if (cp < TRACKED_TABLE_END) return TRACKED_LOW[cp];
  return TRACKED_INVISIBLE.get(cp) ?? CODE_VISIBLE;
}

/** True when `cp` is one of the {@link VS} variation selectors. Read off the
 * class table: VS is exactly the code points classified CODE_VS, which the
 * check below holds the table to, since a Cf code point in VS would be
 * classified CODE_CF and silently stop counting as a selector here.
 * @param {number} cp @returns {boolean} */
function isVariationSelectorCp(cp) {
  return cp >= 0 && classifyCp(cp) === CODE_VS;
}
for (const ch of VS)
  if (!isVariationSelectorCp(/** @type {number} */ (ch.codePointAt(0))))
    throw new Error(
      `variation selector U+${ch.codePointAt(0)?.toString(16)} is not classified CODE_VS`,
    );

// Distinct code points a memoizedCpPredicate will remember. Comfortably above
// the character repertoire of any real document (and of every test corpus here)
// while bounding what a single hostile paste can make one predicate retain.
const CP_PREDICATE_MEMO_CAP = 4096;

/**
 * A code-point predicate backed by a single-code-point RegExp, memoized on the
 * code point.
 *
 * The carve analysis asks these of the same handful of code points over and
 * over — a document is a few hundred distinct characters repeated — and each
 * ask otherwise costs a `String.fromCodePoint` allocation plus a regex match.
 * The memo is a pure accelerator: it answers exactly what the RegExp answers,
 * for the same input, forever.
 *
 * The entry cap is a MEMORY policy, not a scan bound: past it the predicate
 * still answers every code point, just without recording new ones, so no input
 * can change a verdict by overflowing the table — only by giving up the speed-up
 * it would otherwise have had.
 * @param {RegExp} re  single-code-point matcher
 * @returns {(cp: number) => boolean}
 */
function memoizedCpPredicate(re) {
  /** @type {Map<number, boolean>} */
  const memo = new Map();
  return (cp) => {
    if (cp < 0) return false; // past a string boundary: the "" neighbour
    const hit = memo.get(cp);
    if (hit !== undefined) return hit;
    const answer = re.test(String.fromCodePoint(cp));
    if (memo.size < CP_PREDICATE_MEMO_CAP) memo.set(cp, answer);
    return answer;
  };
}

/**
 * `text` as its code points, in the units the String iterator yields — the same
 * sequence `Array.from(text)` produces (an unpaired surrogate stands alone as
 * itself), as numbers rather than one heap-allocated one-character string each.
 * Every carve-analysis predicate reads a code point, so the numbers are the
 * whole requirement: a 256 KB paste that would cost a quarter of a million
 * short-lived strings per pass costs one buffer, and the collector stays out of
 * a blocking hook.
 * @param {string} text
 * @returns {Int32Array}
 */
function codePointArray(text) {
  const cps = new Int32Array(text.length);
  let n = 0;
  for (let i = 0; i < text.length; i++) {
    const unit = text.charCodeAt(i);
    let cp = unit;
    if (unit >= 0xd800 && unit <= 0xdbff && i + 1 < text.length) {
      const low = text.charCodeAt(i + 1);
      if (low >= 0xdc00 && low <= 0xdfff) {
        cp = (unit - 0xd800) * 0x400 + (low - 0xdc00) + 0x10000;
        i++;
      }
    }
    cps[n++] = cp;
  }
  return n === cps.length ? cps : cps.subarray(0, n);
}

/**
 * True when `text` holds at least one code point {@link classifyCp} calls
 * invisible. Walks UTF-16 units directly rather than building the code-point
 * array, so a clean multi-MB paste is answered without allocating anything;
 * surrogates are paired exactly as the String iterator pairs them, an unpaired
 * one classifying as the lone surrogate it is.
 * @param {string} text
 * @returns {boolean}
 */
function hasInvisibleCodePoint(text) {
  for (let i = 0; i < text.length; i++) {
    let cp = text.charCodeAt(i);
    if (cp >= 0xd800 && cp <= 0xdbff && i + 1 < text.length) {
      const low = text.charCodeAt(i + 1);
      if (low >= 0xdc00 && low <= 0xdfff) {
        cp = (cp - 0xd800) * 0x400 + (low - 0xdc00) + 0x10000;
        i++;
      }
    }
    if (classifyCp(cp) !== CODE_VISIBLE) return true;
  }
  return false;
}

/**
 * The number of code points in `text`, counted by the String iterator itself —
 * the same unit `Array.from(text).length` measures, without the array.
 * @param {string} text
 * @returns {number}
 */
function codePointLength(text) {
  let n = 0;
  const iterator = text[Symbol.iterator]();
  while (!iterator.next().done) n++;
  return n;
}

/** A cursive-joining letter: Joining_Type dual, right, or left. (C is a join
 * control, T is a transparent mark, U is non-joining — none is a letter that a
 * ZWNJ/ZWJ does rendering work between.)
 * @param {string} jt @returns {boolean} */
const isCursiveLetter = (jt) => jt === "D" || jt === "R" || jt === "L";

// The three ./joining-type.mjs tables, the three emoji tables and the
// ideograph tables, each read once per distinct code point below
// CP_PROPS_END — the BMP and the SMP, where every joining script, virama and
// emoji lives — and then by array index. The carve analysis asks them about every joiner's neighbours,
// every visible character of a joiner-dense text and every emoji chain's
// components, so a binary search per ask was the analysis' largest cost on
// Persian prose and on a page of ZWJ sequences. Each entry packs the
// Joining_Type's index into JOINING_TYPES (never 0, so 0 means "not yet
// asked") with one bit per yes/no table. Above the end the tables are searched
// directly, so nothing past it is answered differently. Allocated on first use:
// text with no joiner or selector never asks.
const CP_PROPS_END = 0x20000;
const JOINING_TYPES = ["", "C", "D", "R", "L", "T", "U"];
const PROP_TYPE_MASK = 0b111;
const PROP_VIRAMA = 0b1000;
const PROP_BRAHMIC_CONSONANT = 0b10000;
const PROP_EMOJI_TEXT_DEFAULT = 0b100000;
const PROP_EMOJI_MODIFIER = 0b1000000;
const PROP_CJK_IDEOGRAPH = 0b10000000;
const PROP_EXTENDED_PICTOGRAPHIC = 0b100000000;
/** @type {Uint16Array | null} */
let cpPropsTable = null;

/** The packed table entry for `cp` (0 <= cp < CP_PROPS_END).
 * @param {number} cp @returns {number} */
function cpProps(cp) {
  cpPropsTable ??= new Uint16Array(CP_PROPS_END);
  const known = cpPropsTable[cp];
  if (known !== 0) return known;
  const type = JOINING_TYPES.indexOf(joiningType(cp));
  if (type < 1)
    throw new Error(`unknown Joining_Type for U+${cp.toString(16)}`);
  const props =
    type |
    (isVirama(cp) ? PROP_VIRAMA : 0) |
    (isBrahmicConsonant(cp) ? PROP_BRAHMIC_CONSONANT : 0) |
    (inSpans(EMOJI_TEXT_DEFAULT, cp) ? PROP_EMOJI_TEXT_DEFAULT : 0) |
    (inSpans(EMOJI_MODIFIER, cp) ? PROP_EMOJI_MODIFIER : 0) |
    (inCjkIdeographTables(cp) ? PROP_CJK_IDEOGRAPH : 0) |
    (inSpans(EXTENDED_PICTOGRAPHIC, cp) ? PROP_EXTENDED_PICTOGRAPHIC : 0);
  cpPropsTable[cp] = props;
  return props;
}

/** The Joining_Type of a code point, or "U" for -1 (past a string boundary).
 * @param {number} cp @returns {string} */
function jtOf(cp) {
  if (cp < 0) return "U";
  if (cp >= CP_PROPS_END) return joiningType(cp);
  return JOINING_TYPES[cpProps(cp) & PROP_TYPE_MASK];
}

/** True when `cp` is a virama (see ./joining-type.mjs).
 * @param {number} cp @returns {boolean} */
function isViramaCp(cp) {
  if (cp >= CP_PROPS_END) return isVirama(cp);
  return (cpProps(cp) & PROP_VIRAMA) !== 0;
}

/** True when `cp` is itself a ZWNJ/ZWJ (used to reject joiner runs).
 * @param {number} cp @returns {boolean} */
function isJoinControl(cp) {
  return cp === ZWNJ || cp === ZWJ;
}

/**
 * The nearest neighbour of index `i` in direction `dir`, skipping Transparent
 * (combining-mark) code points, as the Unicode cursive-joining algorithm does —
 * a harakat between a letter and a ZWNJ does not break the join. Also skips any
 * OTHER tracked invisible that is itself removable (blank fillers, format
 * chars): it does no cursive-shaping work and gets stripped, so a joiner's real
 * neighbour is the next surviving character. Without this a payload byte wedged
 * between two joiners hides the joiner-RUN until a first pass removes it, after
 * which a second pass strips the now-adjacent joiners — non-idempotent. Join
 * controls (ZWNJ/ZWJ) are deliberately NOT skipped: they are the run signal.
 * Returns -1 past the string boundary (the old "" neighbour).
 * @param {Int32Array} cps @param {number} i @param {number} dir  -1 or +1
 * @returns {number}
 */
function effectiveNeighbor(cps, i, dir) {
  for (let j = i + dir; j >= 0 && j < cps.length; j += dir) {
    const cp = cps[j];
    if (jtOf(cp) === "T") continue;
    if (!isJoinControl(cp) && classifyCp(cp) !== CODE_VISIBLE) continue;
    return cp;
  }
  return -1;
}

/**
 * True when the joiner at `cps[i]` follows a virama that itself sits on a real
 * Brahmic consonant — a genuine half-form/conjunct request (क् + ZWJ), not a
 * bare or base-less halant (a smuggling channel a raw `cps[i-1]` virama test
 * would wave through). Steps left over removable invisibles to LAND on the
 * virama (which is Joining_Type Transparent, so it is the anchor, never skipped),
 * then uses effectiveNeighbor to find the consonant base past any transparent
 * marks / invisibles between it and the virama.
 * @param {Int32Array} cps @param {number} i
 * @returns {boolean}
 */
function followsBrahmicConjunct(cps, i) {
  let j = i - 1;
  while (
    j >= 0 &&
    !isJoinControl(cps[j]) &&
    classifyCp(cps[j]) !== CODE_VISIBLE
  )
    j--;
  if (j < 0 || !isViramaCp(cps[j])) return false;
  return isBrahmicConsonantCp(effectiveNeighbor(cps, j, -1));
}

/**
 * How many VISIBLE code points of `cps` are letters a joiner does rendering work
 * beside: cursive letters (Joining_Type D/R/L) and Brahmic consonants. This is
 * the cover text that funds the joiner allowance past PRESERVE_HARD_CAP — only
 * a script whose orthography uses joiners can buy room for more of them.
 * @param {Int32Array} cps @param {Uint8Array} codes
 * @returns {number}
 */
function joiningLetterCount(cps, codes) {
  let letters = 0;
  for (let i = 0; i < cps.length; i++)
    if (codes[i] === CODE_VISIBLE && isJoiningLetter(cps[i])) letters++;
  return letters;
}

/** A letter a joiner does rendering work beside: a cursive letter or a Brahmic
 * consonant. ASCII is neither, and answers without a lookup.
 * @param {number} cp @returns {boolean} */
function isJoiningLetter(cp) {
  return cp >= 0x80 && (isCursiveLetter(jtOf(cp)) || isBrahmicConsonantCp(cp));
}

/**
 * True when the ZWJ at `cps[i]` sits between a Brahmic consonant and the virama
 * that follows it — the <consonant, ZWJ, virama> spelling Unicode prescribes for
 * the Bengali RA with ya-phala (U+09B0 ZWJ U+09CD U+09AF, not a reph), the
 * Devanagari eyelash RA (U+0930 ZWJ U+094D) and the Sinhala touching letters
 * (U+0D9A ZWJ U+0DCA U+0DC0). The joiner selects which form
 * of the conjunct the virama opens, so it does rendering work. Steps right over
 * removable invisibles to LAND on the virama — the mirror of
 * {@link followsBrahmicConjunct} — so stripping them cannot flip the decision.
 * @param {Int32Array} cps @param {number} i
 * @returns {boolean}
 */
function precedesBrahmicVirama(cps, i) {
  if (cps[i] !== ZWJ) return false;
  let j = i + 1;
  while (
    j < cps.length &&
    !isJoinControl(cps[j]) &&
    classifyCp(cps[j]) !== CODE_VISIBLE
  )
    j++;
  if (j >= cps.length || !isViramaCp(cps[j])) return false;
  return isBrahmicConsonantCp(effectiveNeighbor(cps, i, -1));
}

/**
 * True when the joiner at `cps[i]` does real rendering work and so must be
 * preserved rather than stripped, decided from the neighbours' Joining_Type:
 *   - emoji ZWJ: between two emoji components (its left pictograph may sit behind
 *     a VS16, so step over selectors — see leftNonSelector);
 *   - Indic joiner: after a virama that sits on a real Brahmic consonant, or a
 *     ZWJ between a consonant and the virama that follows it;
 *   - Arabic-family joiner: between two cursive letters (ZWNJ needs both, ZWJ at
 *     least one — it forces a connected form). A joiner whose effective neighbour
 *     is ANOTHER joiner is a run (a zero-width payload channel) and is rejected.
 * Leading/trailing joiners fall out because the -1 boundary has Joining_Type U.
 * @param {Int32Array} cps @param {number} i
 * @returns {boolean}
 */
function isPreservedJoiner(cps, i) {
  const cp = cps[i];
  if (cp !== ZWNJ && cp !== ZWJ) return false;
  // Emoji ZWJ sequences use ZWJ only; the real neighbours are the pictographs,
  // which may each sit behind a variation selector (🏳️‍🌈 = base VS16 ZWJ rainbow;
  // a selector can also follow the ZWJ before the next base), so step over
  // selectors on BOTH sides — leftNonSelector and its mirror rightNonSelector.
  if (
    cp === ZWJ &&
    isEmojiLeft(leftNonSelector(cps, i)) &&
    isEmojiBase(rightNonSelector(cps, i))
  )
    return true;
  // Indic: meaningful only beside a virama that sits on a real consonant base.
  if (followsBrahmicConjunct(cps, i) || precedesBrahmicVirama(cps, i))
    return true;
  // Arabic-family cursive joining, on the nearest non-Transparent neighbours.
  const left = effectiveNeighbor(cps, i, -1);
  const right = effectiveNeighbor(cps, i, 1);
  if (isJoinControl(left) || isJoinControl(right)) return false; // joiner run
  const lc = isCursiveLetter(jtOf(left));
  const rc = isCursiveLetter(jtOf(right));
  return cp === ZWNJ ? lc && rc : lc || rc;
}

/**
 * True when `cps[i]` is a presentation selector (VS15 U+FE0E or VS16 U+FE0F)
 * that is part of a visible glyph, not a hidden VS run:
 *   - directly after a pictograph/skin-tone modifier, preserved; OR
 *   - directly after a keycap base (digit/`#`/`*`) AND immediately followed by
 *     U+20E3 COMBINING ENCLOSING KEYCAP — a complete keycap glyph (1️⃣ #️⃣ …).
 * A keycap base + selector with NO trailing U+20E3 is a bare hidden presentation
 * selector, so it fails closed and is stripped. A longer selector run still
 * surfaces: the next selector's left neighbour is itself a selector.
 * @param {Int32Array} cps @param {number} i
 * @returns {boolean}
 */
function isEmojiPresentationSelector(cps, i) {
  if (!PRESENTATION_SELECTORS.has(cps[i])) return false;
  const prev = i > 0 ? cps[i - 1] : -1;
  if (isEmojiLeft(prev)) return true;
  return (
    isKeycapBase(prev) &&
    (i + 1 < cps.length ? cps[i + 1] : -1) === COMBINING_KEYCAP
  );
}

/**
 * Per-invisible carve-out analysis, shared by carveStrip and
 * countPayloadInvisible: for each code point, its CODE_* class (CODE_VISIBLE
 * when visible) and its preserve KIND_* (KIND_NONE when the char is payload).
 * Everything invisible that is NOT preserve-eligible is payload; the scatter
 * floor counts only that, so meaningful joiners/selectors never push honest
 * prose over the threshold.
 * @param {Int32Array} cps
 * @returns {{ codes: Uint8Array, kind: Uint8Array, invisible: Int32Array, payloadInvis: number, visibleLen: number }}
 */
function analyzeCarve(cps) {
  const codes = new Uint8Array(cps.length);
  // Indices of the invisibles, so every pass below is O(invisibles) rather than
  // O(length): in ordinary text they are a vanishing fraction of a paste, and a
  // full-length pass per preserve rule is what made the analysis linear in the
  // WHOLE prompt several times over.
  let invisCount = 0;
  let visibleLen = 0;
  let hasTagBase = false;
  for (let i = 0; i < cps.length; i++) {
    const code = classifyCp(cps[i]);
    codes[i] = code;
    if (code !== CODE_VISIBLE) {
      invisCount++;
      continue;
    }
    visibleLen++;
    hasTagBase ||= cps[i] === TAG_BASE;
  }
  // Sized exactly, from the count the pass above already produced: a growable
  // array reallocates its way up through a document that is mostly invisible,
  // and that churn is the collector's whole share of this function.
  const invisible = new Int32Array(invisCount);
  for (let i = 0, at = 0; at < invisCount; i++)
    if (codes[i] !== CODE_VISIBLE) invisible[at++] = i;
  // A tag sequence is preservable only when it opens on a TAG_BASE pictograph,
  // so with no base in the text markTagSequences returns all-false.
  const tagKeep = hasTagBase ? markTagSequences(cps) : null;
  const kind = new Uint8Array(cps.length);
  for (const i of invisible) {
    if (tagKeep !== null && tagKeep[i]) kind[i] = KIND_GLYPH;
    else if (isPreservedJoiner(cps, i)) kind[i] = KIND_JOINER;
    else if (isEmojiPresentationSelector(cps, i)) kind[i] = KIND_EMOJIVS;
    else if (isStandardizedVariationSelector(cps, i)) kind[i] = KIND_STDVS;
    else if (isIdeographicVariationSelector(cps, i)) kind[i] = KIND_IVS;
    else if (isPreservedBlankFiller(cps, i)) kind[i] = KIND_BLANK;
  }
  markRegisteredGlyphs(cps, invisible, kind);
  // Blank fillers are budgeted here, document-wide and all-or-nothing, against
  // the visible anchor-script text rather than against the joiner/selector
  // counter in carveStrip (see PRESERVED_BLANK_PER_ANCHOR for why the two
  // cannot share a density model). Deciding it in analyzeCarve rather than in
  // the emit loop keeps countPayloadInvisible and payloadInvisibleView honest:
  // a blank the stripper will remove is payload to every consumer, so the
  // prompt layer's scatter gate sees it without re-deriving the budget.
  //
  // Budgeted PER SCRIPT, because a blank never anchors cross-script: pooling the
  // two anchor counts would let one script's cover text fund the other's
  // channel, so 400 chars of ordinary Korean prose would buy an unreported
  // `⠃⠀⠃⠀…` alternation of 200 Braille blanks. The anchor scan is skipped below
  // the floor: it costs a script regex per visible character, and analyzeCarve
  // runs on every prompt and tool output.
  /** @type {Record<string, number[]>} */
  const blankIndices = { braille: [], hangul: [] };
  for (const i of invisible)
    if (kind[i] === KIND_BLANK)
      blankIndices[cps[i] === BRAILLE_BLANK ? "braille" : "hangul"].push(i);
  for (const [
    script,
    isAnchor,
  ] of /** @type {[string, (cp: number) => boolean][]} */ ([
    ["braille", isBrailleCell],
    ["hangul", isHangul],
  ])) {
    const indices = blankIndices[script];
    if (indices.length <= TOTAL_PRESERVED_BLANK_BUDGET) continue;
    let anchors = 0;
    for (let i = 0; i < cps.length; i++)
      if (codes[i] === CODE_VISIBLE && isAnchor(cps[i])) anchors++;
    if (indices.length > Math.floor(anchors / PRESERVED_BLANK_PER_ANCHOR))
      for (const i of indices) kind[i] = KIND_NONE;
  }
  let payloadInvis = 0;
  for (const i of invisible) if (kind[i] === KIND_NONE) payloadInvis++;
  return { codes, kind, invisible, payloadInvis, visibleLen };
}

/**
 * Count the PAYLOAD invisible code points in `text`: those the carve-out would
 * strip, excluding ZWNJ/ZWJ (and emoji VS16) that do real rendering work.
 * Consumers that gate on invisible density (e.g. the prompt classifier's scatter
 * threshold) use this so legitimate dense multilingual prose is not mistaken for
 * a hidden channel.
 * @param {string} text
 * @returns {number}
 */
export function countPayloadInvisible(text) {
  // Payload is a SUBSET of the invisibles (analyzeCarve counts only positions
  // classifyCp marks invisible), so a text with none has a payload count of zero
  // and needs neither the code-point array nor the carve analysis. This reads
  // every code point — it is a necessary condition checked in full, not a scan
  // bound an attacker could paste past.
  if (!hasInvisibleCodePoint(text)) return 0;
  return carveOf(text).analysis.payloadInvis;
}

/**
 * Bulk strip (the common path: {@link needsCarveOut} found nothing the
 * carve-out could apply to; also the carve-free fallback a non-converging
 * composition asks for). A single regex pass removes every payload-
 * capable char; `found` names the category codes present via `.search`
 * (which ignores the `g` lastIndex).
 * @param {string} body
 * @returns {{ cleaned: string, found: string[] }}
 */
function bulkStrip(body) {
  const found = CHECKS.filter(([, re]) => body.search(re) !== -1).map(
    ([code]) => code,
  );
  return { cleaned: body.replace(STRIP, ""), found };
}

/**
 * The nearest code point left of index `i` that is not a variation selector, or
 * -1 at the string start. An emoji ZWJ sequence can place a VS16 between the base
 * pictograph and the ZWJ, so the joiner's real left neighbor is found by stepping
 * over any variation selector(s).
 * @param {Int32Array} cps
 * @param {number} i
 * @returns {number}
 */
function leftNonSelector(cps, i) {
  let p = i - 1;
  while (p >= 0 && isVariationSelectorCp(cps[p])) p--;
  return p >= 0 ? cps[p] : -1;
}

/**
 * The nearest code point right of index `i` that is not a variation selector, or
 * -1 at the string end. Mirror of {@link leftNonSelector}: an emoji ZWJ can be
 * followed by a selector before the next component's base pictograph, so the
 * joiner's real right neighbor is found by stepping over any variation
 * selector(s).
 * @param {Int32Array} cps
 * @param {number} i
 * @returns {number}
 */
function rightNonSelector(cps, i) {
  let p = i + 1;
  while (p < cps.length && isVariationSelectorCp(cps[p])) p++;
  return p < cps.length ? cps[p] : -1;
}

/**
 * Mark every index that belongs to a PRESERVABLE emoji tag sequence (subregional
 * flag): a U+1F3F4 tag_base, then tag chars in U+E0020–U+E007E whose decoded
 * ASCII payload names a REGISTERED subdivision, then U+E007F CANCEL TAG. Only the
 * tag chars and the terminating CANCEL are marked (the base is a visible
 * pictograph). A run missing the CANCEL, exceeding the tag-char cap, or whose
 * payload is not a registered subdivision is left unmarked so it is stripped —
 * grammatical validity alone is NOT enough, since a valid run spells arbitrary
 * ASCII (fail closed on the top ASCII-smuggling vector).
 * @param {Int32Array} cps
 * @returns {Uint8Array} keep[i] non-zero iff `cps[i]` is inside a preservable tag sequence
 */
function markTagSequences(cps) {
  const keep = new Uint8Array(cps.length);
  for (let i = 0; i < cps.length; i++) {
    if (cps[i] !== TAG_BASE) continue;
    let j = i + 1;
    let payload = "";
    while (j < cps.length && cps[j] >= TAG_SPEC_MIN && cps[j] <= TAG_SPEC_MAX) {
      payload += String.fromCharCode(cps[j] - 0xe0000);
      j++;
    }
    const tagLen = j - (i + 1);
    // Require ≥1 tag char, at most MAX_TAG_SPEC_CHARS, a terminating CANCEL, and
    // a payload naming a registered subdivision — else the run stays stripped.
    if (
      tagLen >= 1 &&
      tagLen <= MAX_TAG_SPEC_CHARS &&
      j < cps.length &&
      cps[j] === TAG_CANCEL &&
      REGISTERED_TAG_PAYLOADS.has(payload)
    ) {
      for (let k = i + 1; k <= j; k++) keep[k] = 1;
      i = j; // resume after the consumed sequence
    }
  }
  return keep;
}

// The selectors the registered sequences use span this range; anything outside
// it (the ideographic selectors among them) is not one, without a lookup.
const STANDARDIZED_SELECTOR_MIN = Math.min(
  ...STANDARDIZED_VARIANTS.map(([, selector]) => selector),
);
const STANDARDIZED_SELECTOR_MAX = Math.max(
  ...STANDARDIZED_VARIANTS.map(([, selector]) => selector),
);

/**
 * True when `cps[i]` is a variation selector whose immediately preceding code
 * point forms a REGISTERED standardized variation sequence with it (per the
 * generated UCD table: VS1–VS14 and the Mongolian free variation selectors).
 * Every unregistered pairing stays payload.
 * @param {Int32Array} cps @param {number} i
 * @returns {boolean}
 */
function isStandardizedVariationSelector(cps, i) {
  const cp = cps[i];
  if (cp < STANDARDIZED_SELECTOR_MIN || cp > STANDARDIZED_SELECTOR_MAX)
    return false;
  return i > 0 && isStandardizedVariant(cps[i - 1], cp);
}

/**
 * True when `cps[i]` is an ideographic variation selector (VS17–VS256,
 * U+E0100–U+E01EF) immediately after a CJK ideograph — the registry-faithful
 * structural gate for an ideographic variation sequence.
 * @param {Int32Array} cps @param {number} i
 * @returns {boolean}
 */
function isIdeographicVariationSelector(cps, i) {
  const cp = cps[i];
  if (cp < IVS_MIN || cp > IVS_MAX) return false;
  return isCjkIdeograph(i > 0 ? cps[i - 1] : -1);
}

/**
 * True when `cps[i]` is a Braille blank (U+2800) or a Hangul filler that sits
 * next to a real, script-appropriate visible neighbour — a genuine empty Braille
 * cell or archaic-Korean filler, not a hidden run. The zero-width Mn marks in
 * BLANK_NON_CF have no such anchored use and are never preserved here.
 * @param {Int32Array} cps @param {number} i
 * @returns {boolean}
 */
function isPreservedBlankFiller(cps, i) {
  const cp = cps[i];
  const prev = i > 0 ? cps[i - 1] : -1;
  const next = i + 1 < cps.length ? cps[i + 1] : -1;
  if (cp === BRAILLE_BLANK) return isBrailleCell(prev) || isBrailleCell(next);
  if (HANGUL_FILLERS.has(cp)) return isHangul(prev) || isHangul(next);
  return false;
}

// The grapheme segmenter: the real UAX #29 implementation shipped with the
// runtime's ICU, not a hand-rolled approximation of cluster boundaries. It
// defines the unit the preserve budget is charged against (see carveStrip).
// Grapheme segmentation is locale-independent, so the locale is pinned to "en"
// only for determinism across hosts.
//
// Built on FIRST USE, never at import: constructing it loads ICU's segmentation
// tables and costs ~10 ms, the largest single item in this module's setup, and
// only text with carve candidates ever reaches clusterResolver. The hooks that
// import this run on every tool call, so building it at import charged every
// call for a segmenter almost none of them use.
/** @type {Intl.Segmenter | null} */
let segmenterCache = null;

/** @returns {Intl.Segmenter} the process-wide grapheme segmenter. */
function graphemeSegmenter() {
  segmenterCache ??= new Intl.Segmenter("en", { granularity: "grapheme" });
  return segmenterCache;
}

/**
 * The UTF-16 index at which each code point of `cps` starts, plus one final
 * entry for the end of the string — the bridge between the code-point space the
 * carve analysis works in and the UTF-16 space `body.slice` and the segmenter
 * speak.
 * @param {Int32Array} cps
 * @returns {Int32Array}
 */
function u16Offsets(cps) {
  const offsets = new Int32Array(cps.length + 1);
  let at = 0;
  for (let i = 0; i < cps.length; i++) {
    offsets[i] = at;
    at += cps[i] > 0xffff ? 2 : 1;
  }
  offsets[cps.length] = at;
  return offsets;
}

/**
 * The code-point index of the UTF-16 index `u16`, by binary search over
 * {@link u16Offsets}. `u16` is always a code-point (indeed a cluster) boundary,
 * so the search always lands exactly.
 * @param {Int32Array} offsets @param {number} u16
 * @returns {number}
 */
function cpIndexOf(offsets, u16) {
  let lo = 0;
  let hi = offsets.length - 1;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (offsets[mid] < u16) lo = mid + 1;
    else hi = mid;
  }
  return lo;
}

/**
 * True when a code point can only ever meet its left neighbour under a rule of
 * UAX #29 that reads those two code points and nothing else.
 *
 * Every grapheme-break rule but three is a property of the PAIR either side of
 * the position (GB3–GB9b). The other three read further left — GB9c (a
 * conjunct: consonant, linker … consonant), GB11 (an emoji ZWJ sequence) and
 * GB12/13 (regional-indicator pairs) — and each fires only when the code point
 * on the RIGHT is, respectively, an Indic consonant, an Extended_Pictographic,
 * or a regional indicator. Below U+0900 there is no Indic consonant and no
 * regional indicator in any Unicode version, and the only pictographs are
 * U+00A9 and U+00AE. ZWNJ and ZWJ, the variation selectors, the tag
 * characters and the CJK ideographs are none of the three in any version
 * either — the pinned ideograph tables name code points that the segmenter's
 * own Unicode, older or newer, has as ideographs or as unassigned outside
 * every emoji block. So when the right-hand code point is one of these, the
 * verdict the segmenter gives the PAIR alone is the verdict it gives the pair
 * in any context.
 *
 * Surrogates are left out: a lone one is a code point here but not to the
 * segmenter, which reads the UTF-16 it is handed.
 * @param {number} cp @returns {boolean}
 */
function contextFreeOnLeft(cp) {
  if (cp < 0x900) return cp !== 0xa9 && cp !== 0xae;
  if (cp === ZWNJ || cp === ZWJ) return true;
  if (cp >= 0xfe00 && cp <= 0xfe0f) return true; // VS1–VS16
  if (cp >= 0xe0020 && cp <= 0xe007f) return true; // tag characters
  if (cp >= 0xe0100 && cp <= 0xe01ef) return true; // VS17–VS256
  return isCjkIdeograph(cp);
}

// Distinct (left, right) pairs pairBreak remembers. Past the cap it declines,
// and the caller asks the segmenter about the whole cluster instead.
const PAIR_BREAK_MEMO_CAP = 4096;
/** @type {Map<number, boolean>} */
const PAIR_BREAK_MEMO = new Map();

/**
 * Whether the segmenter puts a grapheme boundary between `left` and `right`,
 * when that answer cannot depend on anything further left (see
 * {@link contextFreeOnLeft}) — or null when it might, or the pair is new and
 * the memo is full. The answer is the segmenter's own, read off the two-code-
 * point string once per distinct pair, so no break rule is spelled here.
 * @param {number} left @param {number} right
 * @returns {boolean | null}
 */
function pairBreak(left, right) {
  if (!contextFreeOnLeft(right) || (left >= 0xd800 && left <= 0xdfff))
    return null;
  const key = left * 0x110000 + right;
  const hit = PAIR_BREAK_MEMO.get(key);
  if (hit !== undefined) return hit;
  if (PAIR_BREAK_MEMO.size >= PAIR_BREAK_MEMO_CAP) return null;
  const pair = String.fromCodePoint(left, right);
  const first = /** @type {{ segment: string }} */ (
    graphemeSegmenter().segment(pair).containing(0)
  );
  const breaks = first.segment.length < pair.length;
  PAIR_BREAK_MEMO.set(key, breaks);
  return breaks;
}

/**
 * The grapheme cluster containing code point `at`, read off {@link pairBreak}
 * outward from it — or null as soon as one position on either side has no
 * context-free verdict, for the segmenter to answer instead. The start and end
 * of the text are boundaries (GB1, GB2).
 * @param {Int32Array} cps @param {number} at
 * @returns {{ start: number, end: number } | null}
 */
function localCluster(cps, at) {
  let start = at;
  for (; start > 0; start--) {
    const breaks = pairBreak(cps[start - 1], cps[start]);
    if (breaks === null) return null;
    if (breaks) break;
  }
  let end = at + 1;
  for (; end < cps.length; end++) {
    const breaks = pairBreak(cps[end - 1], cps[end]);
    if (breaks === null) return null;
    if (breaks) break;
  }
  return { start, end };
}

// Above this share of the code points being carve-out CANDIDATES, resolving each
// candidate's cluster with `Segments.containing` costs more than segmenting the
// document once from the start (a `containing` call is a few times dearer than
// one step of the sequential iterator). Both strategies read the SAME segmenter,
// so they return the same boundaries; this only picks the cheaper way to ask.
const CONTAINING_CANDIDATE_SHARE = 4;

/**
 * A source of the grapheme cluster containing a given code-point index, over
 * indices asked for in increasing order.
 *
 * Cluster boundaries matter only where a preservable invisible sits: a cluster
 * with none leaves every counter in {@link carveStrip} untouched, and the emit
 * loop treats each of its code points the same however the boundaries fall. So
 * the clusters are resolved on demand around the candidates rather than by
 * segmenting the whole document — the difference between reading one emoji at
 * the end of an 8 MB log and segmenting the 8 MB.
 *
 * Every candidate is first resolved locally, from {@link pairBreak}'s
 * verdicts on the code points either side of it, and only falls back to the
 * segmenter where a verdict is missing — `Segments.containing` when candidates
 * are sparse, a forward walk when they are dense. A `containing` call is a
 * couple of microseconds, and a long Persian document keeps a joiner every few
 * words, so asking the segmenter about each one was most of what carving it
 * cost; a page of variation-selected ideographs paid a segmenter step per
 * character for the same reason.
 * @param {string} body @param {Int32Array} cps @param {Int32Array} offsets
 * @param {number} candidates
 * @returns {(cp: number) => { start: number, end: number }}
 */
function clusterResolver(body, cps, offsets, candidates) {
  const cpCount = cps.length;
  if (candidates * CONTAINING_CANDIDATE_SHARE < cpCount) {
    /** @type {Intl.Segments | null} */
    let segments = null;
    return (cp) => {
      const local = localCluster(cps, cp);
      if (local !== null) return local;
      segments ??= graphemeSegmenter().segment(body);
      // `offsets[cp]` is inside the string for every code-point index the walk
      // asks about, so the segment always exists.
      const found = /** @type {{ index: number, segment: string }} */ (
        segments.containing(offsets[cp])
      );
      return {
        start: cpIndexOf(offsets, found.index),
        end: cpIndexOf(offsets, found.index + found.segment.length),
      };
    };
  }
  // Dense candidates: where the local verdict is missing, walk the segmenter
  // forward instead, keeping a code-point cursor in step with it so no boundary
  // needs searching for. The cursor only moves forward, and candidates arrive
  // in increasing order, so the walk is one pass however many local answers
  // fall between two asks. The iterator is abandoned wherever the last
  // candidate leaves it, so a document whose preserve budget is spent in its
  // first line is never segmented past it.
  /** @type {Iterator<Intl.SegmentData> | null} */
  let iterator = null;
  let start = 0;
  let end = 0;
  return (cp) => {
    const local = localCluster(cps, cp);
    if (local !== null) return local;
    iterator ??= graphemeSegmenter().segment(body)[Symbol.iterator]();
    while (end <= cp) {
      // ECMA-402 guarantees the segments partition the input, so every code
      // point inside it has a cluster and the iterator cannot run out first; if
      // it ever did, reading `.segment` off `undefined` throws here rather than
      // silently answering with a boundary nobody computed.
      const step = /** @type {{ value: { segment: string } }} */ (
        iterator.next()
      );
      start = end;
      end = cpIndexOf(offsets, offsets[start] + step.value.segment.length);
    }
    return { start, end };
  };
}

/**
 * Carve-out strip (an invisible the carve-out might preserve is present): walk
 * GRAPHEME CLUSTERS, preserving a cluster's joiners/selectors/tags only where
 * each has its `kind` set AND the text stays under the scatter floor AND the
 * whole cluster fits inside the remaining per-run (CONSECUTIVE_JOINER_CAP /
 * CONSECUTIVE_SELECTOR_CAP) and document-wide (TOTAL_PRESERVED_JOINER_BUDGET)
 * preserve allowance — otherwise every preservable char in that cluster is
 * stripped like any other payload byte. Blank fillers are the exception: their
 * allowance is anchor-proportional and already spent document-wide in
 * analyzeCarve (see PRESERVED_BLANK_PER_ANCHOR), so here they answer only to
 * the scatter floor and do not draw on the joiner/selector budget.
 *
 * The budget is charged against the CLUSTER, not the code point, because the
 * cluster is the indivisible unit: charging per code point let a limit fall due
 * mid-cluster and carve one grapheme in half (👨‍👩‍👧‍👦 with the budget exhausted
 * after its first ZWJ came out as 👨‍👩👧👦 — three glyphs where the author wrote
 * one). All-or-nothing per cluster makes that impossible by construction rather
 * than merely unlikely, and it subsumes the tag (subregional-flag) sequence's
 * hand-rolled atomicity: a flag's tag chars are Grapheme_Cluster_Break=Extend,
 * so they are already inside their base pictograph's cluster.
 *
 * `found` reports only categories actually removed, so a preserved char never
 * makes the caller claim a strip that did not happen, and a stuffed channel
 * surfaces as its category once it overruns the budget.
 * @param {string} body
 * @param {Int32Array} cps  `body`'s code points
 * @param {ReturnType<typeof analyzeCarve>} analysis  the analysis of `cps`
 * @returns {{ cleaned: string, found: string[], removed: number }}
 */
function carveStrip(body, cps, analysis) {
  const walk = carveWalk(body, cps, analysis, true);
  const kept = /** @type {string[]} */ (walk.kept);
  const found = CHECKS.filter(([code]) => walk.foundCodes.has(code)).map(
    ([code]) => code,
  );
  return { cleaned: kept.join(""), found, removed: walk.removed };
}

/** @param {number} cp @returns {boolean} */
const isHighSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdbff;
/** @param {number} cp @returns {boolean} */
const isLowSurrogate = (cp) => cp >= 0xdc00 && cp <= 0xdfff;

/**
 * How many code points {@link carveStrip} removes from `body`, without
 * building the cleaned text. A verdict needs only this count, and on a page
 * whose budget is spent the cleaned text is one slice per stripped character —
 * the larger part of what the strip cost the gate.
 * @param {string} body @param {Int32Array} cps
 * @param {ReturnType<typeof analyzeCarve>} analysis
 * @returns {number}
 */
function carveRemoved(body, cps, analysis) {
  return carveWalk(body, cps, analysis, false).removed;
}

/**
 * The walk both of the above read (see {@link carveStrip}). With `build`, the
 * kept slices of `body` in order; without, `kept` is null and only the
 * decisions are made.
 * @param {string} body @param {Int32Array} cps
 * @param {ReturnType<typeof analyzeCarve>} analysis @param {boolean} build
 * @returns {{ kept: string[] | null, foundCodes: Set<string | null>, removed: number }}
 */
function carveWalk(body, cps, analysis, build) {
  // Only PAYLOAD invisibles count toward the scatter floor, so a
  // meaningful-joiner-dense text (formal Persian, a long Devanagari conjunct
  // run) stays under it.
  const { codes, kind, invisible, payloadInvis, visibleLen } = analysis;
  // SCATTERED_THRESHOLD is the floor on payload invisibles: past it the document
  // is drowning in hidden bytes, so the carve-out is off and even a meaningful
  // joiner is stripped (threshold-evasion catch — over-strip beats under).
  const allowCarveOut = payloadInvis < SCATTERED_THRESHOLD;
  const n = cps.length;
  // Every code point that draws on the joiner/selector budget, in order. Blank
  // fillers are exempt (their allowance is already spent in analyzeCarve), and
  // so is a glyph's own spelling (KIND_GLYPH), so a cluster holding
  // only those needs no boundary of its own. Read off the invisible indices
  // into a buffer sized for all of them, since only an invisible has a kind.
  const candidateBuffer = new Int32Array(allowCarveOut ? invisible.length : 0);
  let candidateCount = 0;
  if (allowCarveOut)
    for (const k of invisible)
      if (
        kind[k] !== KIND_NONE &&
        kind[k] !== KIND_BLANK &&
        kind[k] !== KIND_GLYPH
      )
        candidateBuffer[candidateCount++] = k;
  const candidates = candidateBuffer.subarray(0, candidateCount);

  // Document-wide preserve allowance, proportional to visible text but never
  // below the floor (see TOTAL_PRESERVED_JOINER_BUDGET / PRESERVED_JOINER_PER_VISIBLE)
  // and never above PRESERVE_HARD_CAP. Every preserved kind draws on it.
  const coverAllowance = Math.min(
    PRESERVE_HARD_CAP,
    Math.max(
      TOTAL_PRESERVED_JOINER_BUDGET,
      Math.ceil(visibleLen / PRESERVED_JOINER_PER_VISIBLE),
    ),
  );
  // The allowance joining letters buy past the cap, for JOINERS alone: a
  // selector or tag beside Persian text does no orthographic work, so letting
  // eight Arabic letters fund one more preserved selector would make the
  // selector channel scale with attacker-supplied cover again. The total of
  // every kind stays under this; the non-joiners also stay under coverAllowance.
  // The joining-letter term is counted only when the candidates outrun the
  // capped allowance AND some of them are joiners: with none, every preserved
  // char also sits under coverAllowance, so the wider total could never bind.
  // Ordinary text, and a selector- or tag-dense one, never pays for the count.
  const joinerAllowance =
    candidates.length <= coverAllowance ||
    !candidates.some((c) => kind[c] === KIND_JOINER)
      ? coverAllowance
      : Math.max(
          coverAllowance,
          Math.ceil(
            joiningLetterCount(cps, codes) / PRESERVED_JOINER_PER_VISIBLE,
          ),
        );

  /** @type {Set<string | null>} */
  const foundCodes = new Set();
  /** @type {string[]} */
  const kept = [];
  // Code points the cleaned text has fewer of than `body`. That is one per
  // stripped code point, plus one wherever the strip closes up a lone high
  // surrogate against a lone low one, which the cleaned string then holds as a
  // single pair — the count the old `[...cleaned].length` difference gave, so
  // the effective count reads the same whether or not the text was built.
  let removed = 0;
  // Whether the code point last walked was stripped, and the one kept just
  // before that stripped stretch began.
  let stripOpen = false;
  let mergeLeft = -1;
  const offsets = u16Offsets(cps);
  // Start of the kept run currently being accumulated, in UTF-16 units. Output
  // is assembled from slices of `body` — one per uninterrupted kept run — rather
  // than a character at a time, so a document with nothing to strip costs one
  // slice however long it is.
  let runStart = 0;
  // Preserved JOINERS in the current uninterrupted cluster (tags/blank fillers
  // and presentation selectors don't chain, so they are exempt). A genuine gap
  // (two visible chars in a row — see prevVisible) resets it; past the cap the
  // surplus is stripped.
  let joinerRun = 0;
  // Preserved IVS/standardized variation selectors in the current uninterrupted
  // run (an `ideograph selector ideograph selector …` chain never breaks the
  // prevVisible gap, so joinerRun's reset does not bound it — this counter does).
  // Same genuine-gap reset as joinerRun; past CONSECUTIVE_SELECTOR_CAP the
  // surplus is stripped, closing the high-bit-rate variation-selector channel.
  let selectorRun = 0;
  // Preserved chars across the WHOLE string — never reset at a gap, so it bounds
  // the document-wide channel joinerRun cannot. Past joinerAllowance a preserved
  // char is stripped and its category reported.
  let preservedTotal = 0;
  // The non-joiner share of preservedTotal, bounded by coverAllowance.
  let preservedOther = 0;
  let prevVisible = false;

  /** Emit `[from, to)` under a settled `fits`, updating every counter.
   * @param {number} from @param {number} to @param {boolean} fits */
  const emit = (from, to, fits) => {
    for (let k = from; k < to; k++) {
      const code = codes[k];
      if (code === CODE_VISIBLE) {
        if (stripOpen) {
          stripOpen = false;
          if (isHighSurrogate(mergeLeft) && isLowSurrogate(cps[k])) removed++;
        }
        // A visible char following another visible char is a real word/segment
        // boundary, not a join — the joined cluster (if any) ended here.
        if (prevVisible) {
          joinerRun = 0;
          selectorRun = 0;
        }
        prevVisible = true;
        continue; // ordinary visible character: stays inside the kept run
      }
      // A blank filler (its own allowance is already spent in analyzeCarve)
      // and a glyph's spelling ride on allowCarveOut alone, and draw
      // on no budget; everything else rides on `fits`.
      const exempt = kind[k] === KIND_BLANK || kind[k] === KIND_GLYPH;
      if (exempt ? allowCarveOut : fits && kind[k] !== KIND_NONE) {
        if (kind[k] === KIND_JOINER) joinerRun++;
        if (kind[k] === KIND_IVS || kind[k] === KIND_STDVS) selectorRun++;
        if (!exempt) preservedTotal++;
        if (!exempt && kind[k] !== KIND_JOINER) preservedOther++;
        prevVisible = false; // a joiner/selector/tag/blank keeps the cluster open
        stripOpen = false;
        continue;
      }
      foundCodes.add(CODE_CATEGORY[code]);
      removed++;
      if (!stripOpen) {
        stripOpen = true;
        mergeLeft = k > 0 ? cps[k - 1] : -1;
      }
      prevVisible = false; // a stripped invisible neither opens nor closes a gap
      if (!build) continue;
      if (offsets[k] > runStart) kept.push(body.slice(runStart, offsets[k]));
      runStart = offsets[k + 1];
    }
  };

  const clusterOf =
    candidates.length > 0
      ? clusterResolver(body, cps, offsets, candidates.length)
      : null;
  // The last index at which the emit loop resets the run counters — a visible
  // code point directly after another visible one. The condition reads only
  // `codes`, never a preserve decision, so the whole set of reset points is
  // known before the walk starts. Past this index the run counters can only
  // ever be incremented, which is what makes the exhaustion test below final.
  let lastGap = -1;
  // Remaining candidates by the limit each one draws on, decremented as the
  // walk passes them.
  let leftJoiner = 0;
  let leftSelector = 0;
  let leftOther = 0;
  if (clusterOf !== null) {
    for (let i = n - 1; i > 0; i--)
      if (codes[i] === CODE_VISIBLE && codes[i - 1] === CODE_VISIBLE) {
        lastGap = i;
        break;
      }
    for (const c of candidates) {
      if (kind[c] === KIND_JOINER) leftJoiner++;
      else if (kind[c] === KIND_IVS || kind[c] === KIND_STDVS) leftSelector++;
      else leftOther++;
    }
  }

  /** True when no cluster from here on can be preserved, so the rest of the
   * document is settled and needs no boundaries. Every term is monotone:
   * `preservedTotal` and `preservedOther` only grow, and past `lastGap` the
   * run counters only grow too, so a limit that is spent here is spent for good.
   * @param {number} at */
  const nothingLeftFits = (at) => {
    if (preservedTotal >= joinerAllowance) return true;
    // Every non-joiner candidate needs room under coverAllowance.
    const othersSpent = preservedOther >= coverAllowance;
    if (othersSpent && leftJoiner === 0) return true;
    if (at <= lastGap) return false; // a reset ahead can reopen a spent run
    if (!othersSpent && leftOther > 0) return false; // a presentation selector draws on neither run
    if (leftJoiner > 0 && joinerRun < CONSECUTIVE_JOINER_CAP) return false;
    if (
      !othersSpent &&
      leftSelector > 0 &&
      selectorRun < CONSECUTIVE_SELECTOR_CAP
    )
      return false;
    return true;
  };

  let k = 0;
  let next = 0;
  while (k < n) {
    while (next < candidates.length && candidates[next] < k) next++;
    if (
      clusterOf === null ||
      next === candidates.length ||
      nothingLeftFits(k)
    ) {
      emit(k, n, false);
      break;
    }
    const { start, end } = clusterOf(candidates[next]);
    if (start > k) emit(k, start, false);
    // Charge the WHOLE cluster's preservables against every limit at once: if
    // any one of them would fall due part-way through, none of the cluster is
    // preserved.
    let need = 0;
    let joiners = 0;
    let selectors = 0;
    for (let j = start; j < end; j++) {
      if (
        kind[j] === KIND_NONE ||
        kind[j] === KIND_BLANK ||
        kind[j] === KIND_GLYPH
      )
        continue;
      need++;
      if (kind[j] === KIND_JOINER) joiners++;
      if (kind[j] === KIND_IVS || kind[j] === KIND_STDVS) selectors++;
    }
    // The run counters as they stand at the cluster's FIRST preservable char.
    // A cluster can OPEN with a genuine gap — two visible code points in a row,
    // e.g. the second of two adjacent emoji ZWJ sequences, or a letter and its
    // harakat — which the emit loop resets on. Judging the caps on the stale
    // pre-reset count would strip joiners the cap never meant to catch: a false
    // positive on legitimate joined text. This mirrors the emit loop's gap rule
    // exactly (only a visible char after another visible char closes a run; any
    // invisible, payload included, does not) and stops at the first preservable,
    // since resets past it are the emit loop's business.
    let runJoiner = joinerRun;
    let runSelector = selectorRun;
    let seenVisible = prevVisible;
    for (let j = start; j < end && kind[j] === KIND_NONE; j++) {
      if (codes[j] === CODE_VISIBLE && seenVisible) {
        runJoiner = 0;
        runSelector = 0;
      }
      seenVisible = codes[j] === CODE_VISIBLE;
    }
    for (let j = next; j < candidates.length && candidates[j] < end; j++) {
      if (kind[candidates[j]] === KIND_JOINER) leftJoiner--;
      else if (
        kind[candidates[j]] === KIND_IVS ||
        kind[candidates[j]] === KIND_STDVS
      )
        leftSelector--;
      else leftOther--;
    }
    emit(
      start,
      end,
      preservedTotal + need <= joinerAllowance &&
        preservedOther + need - joiners <= coverAllowance &&
        runJoiner + joiners <= CONSECUTIVE_JOINER_CAP &&
        runSelector + selectors <= CONSECUTIVE_SELECTOR_CAP,
    );
    k = end;
  }
  if (!build) return { kept: null, foundCodes, removed };
  kept.push(body.slice(runStart));
  return { kept, foundCodes, removed };
}

/**
 * @typedef {{ body: string, cps: Int32Array,
 *   analysis: ReturnType<typeof analyzeCarve>,
 *   strip: { cleaned: string, found: string[], removed: number } | null,
 *   removed: number | null }} CarveEntry
 */

/** @type {CarveEntry | null} */
let lastCarve = null;

/**
 * The carve analysis of `body`, with the most recent one remembered — and the
 * strip, or the count of what it removes, once something has asked for it.
 *
 * One document is often carved more than once per hook call: the prompt gate
 * reads the payload view and the effective count off one string, and when Layer
 * 1's strip leaves the tool output unchanged, {@link isIncidentalInvisible} then
 * asks about that same text. Each reading is the whole analysis, and the
 * effective count the whole walk again. The analysis and the walk are pure
 * functions of `body`, so one remembered entry answers every later reading
 * identically; a miss re-derives it, so the cache can change what a verdict
 * costs and never the verdict.
 *
 * One entry, replaced on every miss, so the retained footprint is the arrays
 * for the document most recently carved — which that call had allocated anyway.
 * The entry is recorded only after the analysis returns, so one that throws
 * leaves the previous document's entry in place rather than a half-built one.
 * @param {string} body
 * @returns {CarveEntry}
 */
function carveOf(body) {
  if (lastCarve !== null && lastCarve.body === body) return lastCarve;
  const cps = codePointArray(body);
  const analysis = analyzeCarve(cps);
  lastCarve = { body, cps, analysis, strip: null, removed: null };
  return lastCarve;
}

// Any tag char (the whole U+E0000–U+E007F block is category Cf).
const TAG_CHAR_RE = /[\u{E0000}-\u{E007F}]/u;

/**
 * True when `body` holds anything the carve-out in {@link carveStrip} might
 * preserve: a ZWNJ/ZWJ, ANY variation selector (a registered standardized or
 * ideographic sequence, or an emoji presentation selector — VARIATION_SELECTOR
 * covers FE00–FE0F and E0100–E01EF), a tag char (a subregional flag), or a
 * gated blank filler (Braille/archaic-Hangul). Each needs the per-neighbor
 * analysis, or bulkStrip would strip it unconditionally and corrupt a
 * legitimate glyph.
 * @param {string} body
 * @returns {boolean}
 */
function needsCarveOut(body) {
  return (
    body.includes(String.fromCodePoint(ZWNJ)) ||
    body.includes(String.fromCodePoint(ZWJ)) ||
    VARIATION_SELECTOR.test(body) ||
    TAG_CHAR_RE.test(body) ||
    GATED_BLANK_RE.test(body)
  );
}

/**
 * The `text` with every visible character and every carve-out-PRESERVABLE
 * invisible (joiners/selectors/tags/blank fillers doing real rendering work)
 * replaced by spaces — one per UTF-16 unit, so the view is index-aligned with
 * `text` — leaving only the PAYLOAD invisibles in place. The LONG_RUN injection
 * probe runs over this so a legitimate emoji/flag/variation sequence never trips
 * the "possible injection payload" marker (alert fatigue), while a genuine
 * hidden run still surfaces.
 * @param {string} text
 * @returns {string}
 */
export function payloadInvisibleView(text) {
  const {
    cps,
    analysis: { codes, kind },
  } = carveOf(text);
  const offsets = u16Offsets(cps);
  /** @param {number} i */
  const isPayload = (i) => codes[i] !== CODE_VISIBLE && kind[i] === KIND_NONE;
  // Written a RUN at a time — one `" ".repeat(n)` per masked stretch, one slice
  // of `text` per payload stretch — because the two stretches alternate a
  // handful of times in a real document and once per character in none of them.
  /** @type {string[]} */
  const parts = [];
  let i = 0;
  while (i < cps.length) {
    const maskFrom = i;
    while (i < cps.length && !isPayload(i)) i++;
    // One space per masked UTF-16 UNIT, so every index into the view is the same
    // index into `text` — a run found here can be located (and line-numbered)
    // in `text` without remapping.
    if (i > maskFrom) parts.push(" ".repeat(offsets[i] - offsets[maskFrom]));
    const keepFrom = i;
    while (i < cps.length && isPayload(i)) i++;
    if (i > keepFrom) parts.push(text.slice(offsets[keepFrom], offsets[i]));
  }
  return parts.join("");
}

/**
 * The first payload-invisible LONG RUN in `text`, or null when there is none.
 *
 * THE definition of "this text carries a hidden run", shared by every consumer
 * that has an opinion about one: the strip's `[LONG RUN — possible injection
 * payload]` marker, the prompt gate's block decision, and the tool-output
 * severity tier. They used to spell it twice, and differently — the marker
 * probed the PAYLOAD view while the prompt gate probed the raw text, so a
 * legitimate ten-emoji flag sequence (carve-out-preserved, never stripped) was
 * quietly enough to BLOCK a prompt while the strip that saw the same text
 * declined to even flag it. Masking the preserved invisibles is the right half
 * of that disagreement: a run the carve-out keeps is rendering work, not a
 * channel, and the joiners it does NOT keep are counted as payload anyway (see
 * {@link countEffectiveInvisible}).
 *
 * Because the view replaces only PRESERVED invisibles (and visible characters)
 * with spaces, a match consists solely of payload code points and is therefore
 * byte-identical to the corresponding span of `text` — so a caller may report
 * the sample verbatim.
 * @param {string} text
 * @returns {string | null}
 */
export function payloadLongRunSample(text) {
  return payloadLongRuns(text).next().value?.text ?? null;
}

/**
 * Every payload-invisible LONG RUN in `text`, in order, as {@link findLongRuns}
 * reports them — `index` is valid in `text` itself, because the view is
 * index-aligned with it.
 * @param {string} text
 * @returns {Generator<{ index: number, text: string, charCount: number }>}
 */
function* payloadLongRuns(text) {
  // The view only ever REPLACES an invisible with a space, so a run in the view
  // is a run in `text`: no long run in the raw text means none in the view. This
  // hides no payload — the bulk scan reads the whole text, and a run it finds
  // still goes through the full carve analysis to decide what of it is payload.
  // With the analysis already in hand the question is answered off it exactly
  // (a view run is a stretch of consecutive payload code points), which is
  // cheaper than the regex on text dense with short preserved runs.
  const known = lastCarve?.body === text ? lastCarve.analysis : null;
  if (known === null ? !hasLongRun(text) : !hasPayloadRun(known)) return;
  yield* findLongRuns(payloadInvisibleView(text));
}

/** Whether the analysis holds {@link LONG_RUN_THRESHOLD} consecutive payload
 * code points — exactly when {@link payloadInvisibleView} holds a long run.
 * @param {ReturnType<typeof analyzeCarve>} analysis @returns {boolean} */
function hasPayloadRun({ invisible, kind }) {
  let run = 0; // payload code points in a row, ending at the previous invisible
  let prev = -2;
  for (const i of invisible) {
    run = kind[i] !== KIND_NONE ? 0 : i === prev + 1 ? run + 1 : 1;
    if (run >= LONG_RUN_THRESHOLD) return true;
    prev = i;
  }
  return false;
}

/**
 * How many invisible code points in `text` the strip layer treats as PAYLOAD:
 * the ones {@link countPayloadInvisible} counts, plus the joiners that sit in a
 * genuine linguistic context but exceed the carve-out's preservation budget.
 *
 * The surplus term closes the preserved-joiner covert channel (O3):
 * `countPayloadInvisible` excludes every ZWNJ/ZWJ doing real rendering work, so
 * an attacker who alternates `letter joiner letter joiner …` — every joiner
 * legitimately between two cursive letters — counts as ZERO there. The strip
 * layer already refuses that (it preserves joiners only up to
 * TOTAL_PRESERVED_JOINER_BUDGET / CONSECUTIVE_JOINER_CAP and strips the rest),
 * so the surplus is read back OFF the strip — the SSOT — rather than by
 * re-deriving the budget here, which is what would drift.
 *
 * A leading BOM is preserved by the strip but counted by
 * {@link countPayloadInvisible}, so the difference can go slightly negative;
 * hence the clamp.
 * @param {string} text  ANSI-stripped text (an escape sequence can hide invisibles)
 * @returns {number}
 */
export function countEffectiveInvisible(text) {
  // A text with no invisible code point has no payload and nothing to strip, so
  // it needs neither the code-point array nor the carve analysis. This reads
  // every code point — a necessary condition checked in full, not a scan bound
  // an attacker could paste past.
  if (!hasInvisibleCodePoint(text)) return 0;
  // A leading BOM is sliced off before the strip but counted by the analysis, so
  // the two would read different strings; that case pays for both separately.
  if (text.charCodeAt(0) === 0xfeff)
    return surplusOver(countPayloadInvisible(text), text, stripInvisible(text));
  // Otherwise both terms are readings of ONE carve analysis of ONE string —
  // the one the strip reads too (see carveOf).
  const entry = carveOf(text);
  const payload = entry.analysis.payloadInvis;
  if (!needsCarveOut(text))
    return surplusOver(
      payload,
      text,
      bulkStrip(text).cleaned,
      entry.cps.length,
    );
  // The count is all this needs: a strip already made answers it, and
  // otherwise the walk makes the same decisions without assembling the text.
  entry.removed ??=
    entry.strip?.removed ?? carveRemoved(text, entry.cps, entry.analysis);
  return payload + Math.max(0, entry.removed - payload);
}

/**
 * The payload count plus the code points the strip removed BEYOND it — the
 * carve-out's over-budget surplus (see {@link countEffectiveInvisible}). A
 * leading BOM is preserved by the strip but counted as payload, so the
 * difference can go slightly negative; hence the clamp.
 * @param {number} payload @param {string} text @param {string} stripped
 * @param {number} [cpLen]  `text`'s code-point length, when already known
 * @returns {number}
 */
function surplusOver(payload, text, stripped, cpLen) {
  // Two identical strings differ by zero code points, so the common clean paste
  // skips both counting passes; codePointLength is the String iterator's count,
  // the same unit `[...text].length` measures, without the array.
  const removed =
    stripped === text
      ? 0
      : (cpLen ?? codePointLength(text)) - codePointLength(stripped);
  return payload + Math.max(0, removed - payload);
}

/**
 * True when the invisible characters in `text` are INCIDENTAL: no hidden run,
 * and too few of them in total to carry an instruction.
 *
 * This is a severity line, not a strip line — the bytes are removed either way
 * (see ../src/severity.mjs). It exists because a single soft hyphen in a
 * pasted paragraph, or one variation selector a font demanded, raised the exact
 * `WARNING: Tool output sanitized` an encoded payload does, and a warning that
 * fires on a stray character in ordinary prose is one operators learn to skip.
 *
 * The bar is {@link LONG_RUN_THRESHOLD} — the count this module already calls
 * "payload length" — applied to the WHOLE text rather than to one run, so it is
 * strictly stronger than the run probe: fewer than ten payload-invisible code
 * points, however they are distributed, cannot spell a smuggled instruction (ten
 * tag characters are ten ASCII letters). Deliberately NOT the far looser
 * {@link SCATTERED_THRESHOLD} of 30, which is the prompt gate's BLOCK bar: 29
 * tag characters is a short sentence, and staying quiet about a short sentence
 * hidden in a tool result is not a trade worth making.
 * @param {string} text  ANSI-stripped text, invisible runs intact
 * @returns {boolean}
 */
export function isIncidentalInvisible(text) {
  return (
    payloadLongRunSample(text) === null &&
    countEffectiveInvisible(text) < LONG_RUN_THRESHOLD
  );
}

/**
 * THE decision whether `text` carries a payload-capable invisible channel: a
 * payload LONG RUN, or {@link SCATTERED_THRESHOLD} or more effective payload
 * invisibles (see {@link countEffectiveInvisible}). The prompt gate's block
 * and the write path's authored-content strip both read this one verdict, so a
 * legitimate emoji ZWJ sequence or a Persian paragraph cannot be a payload to
 * one of them and clean to the other.
 *
 * It stops at the first payload run, which is all a gate needs (the prompt
 * gate quotes it, the write path reads only the boolean), so an 8 MB field of
 * short runs costs one run record rather than one per run. `invisibleCount` is
 * the effective count, so a caller that reports the finding describes exactly
 * what was judged.
 * @param {string} text  the text a consumer acts on, ANSI-stripped where its
 *   surface can carry escapes (a sequence can hide invisibles)
 * @returns {{ firstRun: { index: number, text: string, charCount: number } | null, invisibleCount: number, payloadCapable: boolean }}
 */
export function payloadVerdict(text) {
  // The count first: it carves the text, and the run search then reads that
  // carve rather than scanning the text again (see payloadLongRuns).
  const invisibleCount = countEffectiveInvisible(text);
  const firstRun = payloadLongRuns(text).next().value ?? null;
  return {
    firstRun,
    invisibleCount,
    payloadCapable: firstRun !== null || invisibleCount >= SCATTERED_THRESHOLD,
  };
}

/**
 * Strip payload-capable invisible chars and report which categories were
 * removed. A single leading U+FEFF (BOM) is preserved as a legitimate marker;
 * interior BOMs and all soft hyphens (U+00AD) are stripped, since either can
 * encode hidden instructions. ZWNJ/ZWJ survive only in a linguistic context
 * (see the carve-out above). `found` names exactly the categories stripped, so
 * a caller never warns about a strip the carve-out skipped.
 *
 * `originalText` is the pre-processing text (before any ANSI strip) used ONLY to
 * decide whether a leading BOM is genuinely leading: an interior BOM that an
 * ANSI-strip left at index 0 of `text` (e.g. `ESC[m + interior U+FEFF`) must NOT be treated as a
 * legitimate leading marker. Defaults to `text` for the common single-arg call.
 *
 * `carveOut: false` strips EVERY payload-capable invisible, preserved joiners
 * and selectors included — the monotone strip a caller falls back to when a
 * composition around the carve-out fails to converge (its output holds no
 * invisible at all, so nothing downstream can reconstitute through it).
 * @param {string} text
 * @param {string} [originalText]
 * @param {{ carveOut?: boolean }} [options]
 * @returns {{ cleaned: string, found: string[] }}
 */
export function stripInvisibleWithReport(
  text,
  originalText = text,
  { carveOut = true } = {},
) {
  // Leading only when the BOM leads the ORIGINAL text (not merely `text` after an
  // ANSI strip shifted an interior BOM to index 0). The `text` guard keeps the
  // slice sound when the two disagree.
  const hasLeadingBom =
    originalText.charCodeAt(0) === 0xfeff && text.charCodeAt(0) === 0xfeff;
  const body = hasLeadingBom ? text.slice(1) : text;
  const { cleaned, found } = carveOut ? stripBody(body) : bulkStrip(body);
  return { cleaned: hasLeadingBom ? BOM + cleaned : cleaned, found };
}

/**
 * The strip of a BOM-resolved body: the carve-out walk when anything in it could
 * be preserved, the single bulk regex pass otherwise.
 * @param {string} body
 * @returns {{ cleaned: string, found: string[] }}
 */
function stripBody(body) {
  if (!needsCarveOut(body)) return bulkStrip(body);
  const entry = carveOf(body);
  entry.strip ??= carveStrip(body, entry.cps, entry.analysis);
  // A copy, so a caller that edits its `found` cannot edit the cached one.
  return { cleaned: entry.strip.cleaned, found: [...entry.strip.found] };
}

/**
 * Strip payload-capable invisible chars (cleaned text only). See
 * stripInvisibleWithReport for the BOM and ZWNJ/ZWJ carve-out semantics.
 * @param {string} text
 * @returns {string}
 */
export function stripInvisible(text) {
  return stripInvisibleWithReport(text).cleaned;
}
