#!/usr/bin/env node
/**
 * Build the Claude Code plugin's shipped artifact: one self-contained ESM bundle
 * with every package inlined, so an installed plugin needs no node_modules.
 *
 * The engine is resolved from the REGISTRY, never from this repo's own `src/`:
 * the `sanitizer-engine` devDependency is an npm alias pinning a published
 * agent-sanitizer version, and the esbuild alias below maps the hooks' canonical
 * `agent-sanitizer` specifiers onto it. That is what keeps the committed bundle
 * stable across ordinary source changes — it only moves when the pin moves.
 */
import { build } from "esbuild";
import { existsSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

/** Repo root (this script lives at plugin/scripts/). */
const ROOT = resolve(__dirname, "..", "..");

/** The hook sources the bundle is built from. */
export const PLUGIN_ENTRY = join(ROOT, "claude-hooks", "plugin-hooks.mjs");

/** Committed artifact path. */
export const BUNDLE_PATH = join(
  ROOT,
  "plugin",
  "dist",
  "hooks",
  "plugin-hooks.bundle.mjs",
);

/** Committed Python requirement the SessionStart provisioner installs. */
export const REQUIREMENTS_PATH = join(ROOT, "plugin", "requirements.txt");

// The packages inlined into the bundle. esbuild prefixes each inlined module
// with a `// <path>` comment, and for a pnpm dep that path embeds the
// content-addressed store hash, which varies with the store layout across
// environments and would make a committed bundle differ from a CI rebuild for no
// real reason.
const INLINED_PACKAGES = [
  "agent-control-plane-core",
  "agent-sanitizer",
  "namespace-guard",
];

/**
 * The published engine version the plugin is pinned to, read from the
 * `sanitizer-engine` npm alias in package.json. Throws when the alias is absent
 * or not in `npm:agent-sanitizer@<version>` form — a plugin built against an
 * unknown engine must fail the build, never ship an unpinned bundle.
 * @param {string} [packageJsonText]
 * @returns {string}
 */
export function enginePin(packageJsonText) {
  const pkg = JSON.parse(
    packageJsonText ?? readFileSync(join(ROOT, "package.json"), "utf-8"),
  );
  const spec = pkg.devDependencies?.["sanitizer-engine"];
  const match = /^npm:agent-sanitizer@(?<version>\d+\.\d+\.\d+)$/.exec(
    spec ?? "",
  );
  if (!match)
    throw new Error(
      `package.json: devDependencies.sanitizer-engine must be "npm:agent-sanitizer@<x.y.z>", got ${JSON.stringify(spec)}`,
    );
  // Read the numeric index, not `match.groups.version`: the named group keeps the
  // pattern readable, but `groups` is optional in the type so only the indexed
  // read is statically a string.
  return match[1];
}

/**
 * The generated requirements.txt body: the PyPI half of the same pin, so the
 * redactor daemon the plugin provisions matches the engine it bundled.
 * @param {string} [version]
 * @returns {string}
 */
export function redactorRequirements(version = enginePin()) {
  return (
    "# GENERATED by plugin/scripts/build-plugin.mjs from the sanitizer-engine\n" +
    "# pin in package.json — do not edit by hand.\n" +
    `agent-sanitizer[secrets]==${version}\n`
  );
}

/**
 * Bundle the plugin entry into a self-contained ESM string. Deterministic: no
 * minify (the shipped bytes stay auditable), `node:` builtins left external
 * (present in every target runtime), store paths normalized. esbuild's output
 * for a given version + inputs is byte-stable, which is what lets the
 * reproducibility test compare committed vs freshly built.
 * @returns {Promise<string>}
 */
export async function bundlePluginHook() {
  const version = enginePin();
  const result = await build({
    entryPoints: [PLUGIN_ENTRY],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    // The hooks import the engine by its canonical name so the same sources are
    // publishable as `agent-sanitizer/claude-hooks`; only the bundle resolves
    // that name to the pinned registry copy.
    alias: { "agent-sanitizer": "sanitizer-engine" },
    // Only Node's own builtins may remain as imports in the artifact; everything
    // else is inlined. A bare (non-node:) import surviving here would mean the
    // installed plugin needs a node_modules — the exact thing this bundle exists
    // to avoid — so keep the external set to builtins only.
    external: ["node:*"],
    minify: false,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const [file] = result.outputFiles;
  return (
    `/**\n * GENERATED by plugin/scripts/build-plugin.mjs — do not edit by hand.\n` +
    ` * Built against agent-sanitizer@${version} from the npm registry.\n */\n` +
    normalizeModulePaths(file.text)
  );
}

/**
 * Rewrite esbuild's `// <path>` module labels for the inlined packages to a
 * stable, package-relative form (`// <pkg>/<rest>`), so the reproducibility gate
 * compares actual code, not pnpm store paths. Done with plain string splits (no
 * regex) over the fixed store markers; the entry's own repo-relative label is
 * already stable.
 * @param {string} text
 * @returns {string}
 */
export function normalizeModulePaths(text) {
  return text
    .split("\n")
    .map((line) => {
      if (!line.startsWith("// ")) return line;
      for (const pkg of INLINED_PACKAGES) {
        const marker = `/node_modules/${pkg}/`;
        const idx = line.indexOf(marker);
        if (idx !== -1) return `// ${pkg}/${line.slice(idx + marker.length)}`;
      }
      return line;
    })
    .join("\n");
}

/**
 * The installed root of `specifier`: resolve its main entry, then walk up to the
 * directory holding its package.json. Resolving "<pkg>/package.json" directly
 * would be simpler but these packages restrict their `exports` map, which makes
 * that subpath unresolvable — and the resolution must go through the ESM
 * resolver, since some of them declare only an `import` condition.
 * @param {string} specifier
 * @returns {string}
 */
function packageRoot(specifier) {
  let dir = dirname(fileURLToPath(import.meta.resolve(specifier)));
  for (;;) {
    if (existsSync(join(dir, "package.json"))) return dir;
    const parent = dirname(dir);
    if (parent === dir)
      throw new Error(`no package.json above the entry of ${specifier}`);
    dir = parent;
  }
}

/**
 * The installed directory of each package the un-bundled hooks import by bare
 * specifier, so a test can stage a node_modules that resolves them (the repo
 * installs the engine under its alias, not its own name).
 * @returns {Record<string, string>}
 */
export function packageDirs() {
  return {
    "agent-sanitizer": packageRoot("sanitizer-engine"),
    "agent-control-plane-core": packageRoot("agent-control-plane-core"),
    "namespace-guard": packageRoot("namespace-guard"),
  };
}

/**
 * Write the bundle and requirements.txt, returning whether either changed.
 * @returns {Promise<boolean>}
 */
async function writeArtifacts() {
  const bundle = await bundlePluginHook();
  const requirements = redactorRequirements();
  mkdirSync(dirname(BUNDLE_PATH), { recursive: true });
  let changed = false;
  for (const [path, content] of [
    [BUNDLE_PATH, bundle],
    [REQUIREMENTS_PATH, requirements],
  ]) {
    let existing;
    try {
      existing = readFileSync(path, "utf-8");
    } catch {
      existing = null;
    }
    if (existing === content) continue;
    writeFileSync(path, content);
    changed = true;
  }
  return changed;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const changed = await writeArtifacts();
  process.stdout.write(
    changed
      ? `plugin artifacts regenerated (engine ${enginePin()})\n`
      : `plugin artifacts already current (engine ${enginePin()})\n`,
  );
}
