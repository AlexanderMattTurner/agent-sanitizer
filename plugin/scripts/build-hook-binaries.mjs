/**
 * Compile the committed hook bundle into one self-contained executable per
 * supported platform with `bun build --compile`, and pin their SHA-256 digests
 * in the committed manifest `plugin/dist/hooks/hook-binaries.sha256`.
 *
 * The binaries themselves are never committed (~100 MB each): the release
 * workflow rebuilds them and attaches them to the GitHub release, and the
 * SessionStart provisioner (`provision-hook-binary.sh`) downloads the one for
 * its platform and verifies it against the manifest before installing it. What
 * makes the committed digest the truth for a binary built elsewhere is that
 * `bun build --compile` is byte-deterministic for a fixed (bun version, target,
 * input bundle, outfile name) — so this build, the CI `--check` rebuild, and
 * the release build all produce identical bytes, and the reproducibility gate
 * survives as a digest round-trip even though the artifact lives outside git.
 *
 * Needs the network on a cold cache: bun downloads each cross-target runtime
 * once. The manifest is therefore regenerated by `plugin-dist-autofix.yaml`
 * (`--if-stale`) rather than by the offline pre-commit rebuild, matching how
 * `plugin/requirements.txt` is kept fresh.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { BUNDLE_PATH } from "./build-plugin.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

/** Repo root (this script lives at plugin/scripts/). */
const ROOT = resolve(__dirname, "..", "..");

/** Committed digest manifest, in `sha256sum -c` line format. */
export const MANIFEST_PATH = join(
  ROOT,
  "plugin",
  "dist",
  "hooks",
  "hook-binaries.sha256",
);

/**
 * Release-asset name prefix. The full asset name is the compile outfile name,
 * and bun embeds that name in the binary — so the digests below only hold for
 * files compiled AND published under exactly these names.
 */
export const ASSET_PREFIX = "agent-sanitizer-hooks-";

/** Supported platforms (`uname -s`/`-m` normalized) → bun compile target. */
export const PLATFORMS = Object.freeze({
  "darwin-arm64": "bun-darwin-arm64",
  "darwin-x64": "bun-darwin-x64",
  "linux-arm64": "bun-linux-arm64",
  "linux-x64": "bun-linux-x64",
});

/**
 * SHA-256 hex digest of a file's bytes.
 * @param {string} path
 */
function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

/**
 * The pnpm-pinned bun this repo compiles with. The system PATH's bun would
 * compile fine but at whatever version happens to be installed — and the
 * digest is a function of the bun version, so only the pinned one can
 * reproduce the manifest.
 */
function bunBin() {
  const bin = join(ROOT, "node_modules", ".bin", "bun");
  if (!existsSync(bin))
    throw new Error(`${bin} is missing — run \`pnpm install\` first`);
  return bin;
}

/** The pinned bun's own version report. */
export function installedBunVersion() {
  const res = spawnSync(bunBin(), ["--version"], { encoding: "utf8" });
  if (res.status !== 0)
    throw new Error(`bun --version failed: ${res.stderr ?? ""}`);
  return res.stdout.trim();
}

/**
 * `owner/repo` from package.json's repository.url — the repo whose GitHub
 * releases carry the binaries, so the provisioner's download URL and these
 * digests can never name two different projects. A dot is legal in a repo
 * name, so only a trailing `.git` may be stripped.
 */
export function repositorySlug() {
  const url = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8"))
    .repository.url;
  const match = /github\.com\/(?<slug>[^/]+\/.+?)(?:\.git)?(?:\/|$)/.exec(url);
  if (!match?.groups)
    throw new Error(`package.json repository.url is not a GitHub URL: ${url}`);
  return match.groups.slug;
}

/**
 * Render the manifest. The digest lines are literal `sha256sum -c` input so
 * the provisioner can verify a download with the tool that owns the format;
 * the `key=value` header comments carry what the digests alone cannot say.
 * @param {{bunVersion: string, bundleSha256: string, repository: string,
 *          digests: Record<string, string>}} fields
 * @returns {string}
 */
function renderManifest({ bunVersion, bundleSha256, repository, digests }) {
  const lines = Object.keys(PLATFORMS)
    .map((platform) => `${digests[platform]}  ${ASSET_PREFIX}${platform}`)
    .join("\n");
  return (
    "# GENERATED by plugin/scripts/build-hook-binaries.mjs — do not edit by hand.\n" +
    "# SHA-256 digests of the bun-compiled hook binaries attached to this repo's\n" +
    "# GitHub releases. The binaries are not committed; a downloaded one is\n" +
    "# verified against this file before it is installed.\n" +
    `# repository=${repository}\n` +
    `# bun=${bunVersion}\n` +
    `# bundle=${bundleSha256}\n` +
    `${lines}\n`
  );
}

/**
 * Parse a manifest back into its fields. Exported so tests and the shell
 * provisioner's parity test read the file through one reader instead of each
 * guessing at the format.
 * @param {string} text
 * @returns {{repository: string, bun: string, bundle: string,
 *            digests: Record<string, string>}}
 */
export function parseManifest(text) {
  const header = (/** @type {string} */ key) => {
    const match = new RegExp(`^# ${key}=(?<value>\\S+)$`, "m").exec(text);
    if (!match?.groups)
      throw new Error(`manifest is missing its "# ${key}=" header`);
    return match.groups.value;
  };
  const digests = /** @type {Record<string, string>} */ ({});
  for (const line of text.split("\n")) {
    const match = /^(?<digest>[0-9a-f]{64}) {2}(?<asset>\S+)$/.exec(line);
    if (!match?.groups) continue;
    const { digest, asset } = match.groups;
    if (!asset.startsWith(ASSET_PREFIX))
      throw new Error(`manifest digest line names a foreign asset: ${line}`);
    digests[asset.slice(ASSET_PREFIX.length)] = digest;
  }
  return {
    repository: header("repository"),
    bun: header("bun"),
    bundle: header("bundle"),
    digests,
  };
}

/**
 * Whether the committed manifest already describes THIS tree: same bundle,
 * same pinned bun, same repository. True means a rebuild would reproduce it
 * byte-for-byte, so `--if-stale` skips the compile entirely.
 */
function manifestIsCurrent() {
  if (!existsSync(MANIFEST_PATH)) return false;
  const manifest = parseManifest(readFileSync(MANIFEST_PATH, "utf-8"));
  return (
    manifest.bundle === sha256(BUNDLE_PATH) &&
    manifest.bun === installedBunVersion() &&
    manifest.repository === repositorySlug() &&
    Object.keys(PLATFORMS).every((platform) => manifest.digests[platform])
  );
}

/** The name the compile input is given inside `outdir` — see compileBinaries. */
const COMPILE_INPUT = "plugin-hooks.bundle.mjs";

/**
 * Compile every platform's binary into `outdir` under its release-asset name
 * and return the per-platform digests.
 *
 * cwd is `outdir`, and BOTH the input and the outfile are bare names, because
 * bun embeds each path string exactly as given. An absolute input path is what
 * makes a build reproduce only on the machine that ran it — this repo's
 * checkout lives at a different absolute path than CI's, so the digests would
 * never agree. Copying the bundle in and naming it relatively is what makes
 * the committed manifest verifiable anywhere.
 * @param {string} outdir
 * @returns {Record<string, string>}
 */
function compileBinaries(outdir) {
  mkdirSync(outdir, { recursive: true });
  copyFileSync(BUNDLE_PATH, join(outdir, COMPILE_INPUT));
  const digests = /** @type {Record<string, string>} */ ({});
  for (const [platform, target] of Object.entries(PLATFORMS)) {
    const asset = `${ASSET_PREFIX}${platform}`;
    const res = spawnSync(
      bunBin(),
      [
        "build",
        "--compile",
        `--target=${target}`,
        COMPILE_INPUT,
        "--outfile",
        asset,
      ],
      { cwd: outdir, stdio: ["ignore", "inherit", "inherit"] },
    );
    if (res.status !== 0)
      throw new Error(
        `bun build --compile failed for ${target} (exit ${res.status})`,
      );
    digests[platform] = sha256(join(outdir, asset));
  }
  return digests;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const outdirArg = args
    .find((a) => a.startsWith("--outdir="))
    ?.slice("--outdir=".length);
  if (outdirArg === "") throw new Error("--outdir= needs a path");
  if (args.includes("--if-stale") && manifestIsCurrent()) {
    process.stdout.write("hook-binary manifest already current\n");
    process.exit(0);
  }
  const outdir =
    outdirArg ?? mkdtempSync(join(tmpdir(), "agent-sanitizer-hook-binaries-"));
  try {
    const built = renderManifest({
      bunVersion: installedBunVersion(),
      bundleSha256: sha256(BUNDLE_PATH),
      repository: repositorySlug(),
      digests: compileBinaries(outdir),
    });
    if (args.includes("--check")) {
      const committed = readFileSync(MANIFEST_PATH, "utf-8");
      if (committed !== built)
        throw new Error(
          "committed hook-binary manifest does not match a rebuild from this tree.\n" +
            `--- committed (${MANIFEST_PATH})\n${committed}` +
            `--- rebuilt\n${built}` +
            "Regenerate with `node plugin/scripts/build-hook-binaries.mjs`.",
        );
      process.stdout.write("hook-binary manifest reproduced byte-for-byte\n");
    } else {
      const existing = existsSync(MANIFEST_PATH)
        ? readFileSync(MANIFEST_PATH, "utf-8")
        : null;
      if (existing === built) {
        process.stdout.write("hook-binary manifest already current\n");
      } else {
        writeFileSync(MANIFEST_PATH, built);
        process.stdout.write(
          "hook-binary manifest regenerated from this tree\n",
        );
      }
    }
  } finally {
    if (!outdirArg) rmSync(outdir, { recursive: true, force: true });
  }
}
