#!/usr/bin/env node
/**
 * Generate src/css-syntax-data.mjs: the css-tree grammars of the properties
 * src/html.mjs names in a string literal (plus a vendor-prefixed one's
 * basename) and the closure of what they reference, so the bundle skips
 * css-tree's ~400 KB of mdn-data. A property outside the table is "Unknown" to
 * the lexer, which the cascade treats as valid. Git-ignored and never committed:
 * scripts/gen-unicode.mjs runs this at `pnpm install` and pack time. Re-run
 * (`pnpm gen:unicode`) when test/css-syntax-data.test.mjs reports drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import cssSyntaxData from "css-tree/definition-syntax-data";
import { parse, walk } from "css-tree/definition-syntax";

/** @typedef {{ types: Record<string, string>, properties: Record<string, string> }} CssSyntax */

/** @param {string} [readerSource] @returns {CssSyntax} */
export function deriveCssSyntax(
  readerSource = readFileSync(
    new URL("../src/html.mjs", import.meta.url),
    "utf8",
  ),
) {
  const { types, properties } = cssSyntaxData;
  /** @type {CssSyntax} */
  const out = { types: {}, properties: {} };
  /** @type {Array<[keyof CssSyntax, string]>} */
  const queue = [];
  for (const [, name] of readerSource.matchAll(/"(-?[a-z][a-z-]*)"/g))
    for (const candidate of [name, name.replace(/^-[a-z]+-/, "")])
      queue.push(["properties", candidate]);
  while (queue.length > 0) {
    const [table, name] = /** @type {[keyof CssSyntax, string]} */ (
      queue.pop()
    );
    const source = table === "types" ? types : properties;
    // Already kept, not a property, or a generic type the lexer builds itself.
    if (Object.hasOwn(out[table], name) || !Object.hasOwn(source, name))
      continue;
    out[table][name] = source[name];
    walk(parse(source[name]), (/** @type {any} */ node) => {
      if (node.type === "Type") queue.push(["types", node.name]);
      if (node.type === "Property") queue.push(["properties", node.name]);
    });
  }
  /** @param {Record<string, string>} table */
  const sorted = (table) => Object.fromEntries(Object.entries(table).sort());
  return { types: sorted(out.types), properties: sorted(out.properties) };
}

/** @param {CssSyntax} syntax */
export function renderCssSyntax(syntax) {
  /** @param {Record<string, string>} table */
  const rows = (table) =>
    Object.entries(table)
      .map(
        ([name, grammar]) =>
          `    ${JSON.stringify(name)}: ${JSON.stringify(grammar)},\n`,
      )
      .join("");
  return `/** GENERATED by scripts/gen-css-syntax.mjs — DO NOT EDIT (mdn-data, CC0). */
// Stryker disable all — generated; its correctness is the round-trip test.
/** @type {{ types: Record<string, string>, properties: Record<string, string> }} */
export const CSS_SYNTAX = {
  types: {
${rows(syntax.types)}  },
  properties: {
${rows(syntax.properties)}  },
};
// Stryker restore all
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(
    new URL("../src/css-syntax-data.mjs", import.meta.url),
  );
  const syntax = deriveCssSyntax();
  writeFileSync(out, renderCssSyntax(syntax));
  console.log(
    `wrote ${out}: ${Object.keys(syntax.properties).length} properties, ` +
      `${Object.keys(syntax.types).length} types`,
  );
}
