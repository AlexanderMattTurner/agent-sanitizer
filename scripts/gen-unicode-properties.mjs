#!/usr/bin/env node
/**
 * Generate src/unicode-properties.mjs from the pinned UCD package (see
 * ./lib/ucd.mjs for why every version-dependent property is pinned rather than
 * read from the runtime).
 *
 * The carve-out reads its neighbours' Unicode properties (pictographs, skin
 * tones, text-default emoji, ideographs, Braille, Hangul) and the confusables gate
 * reads combining marks, and each set grows
 * with Unicode: a live `\p{…}` once made Node 22.22 strip the Extension J
 * sequences Node 22.23 preserved. test/unicode-properties.test.mjs re-derives
 * the tables from the same package.
 *
 * Run from the repo root: `node scripts/gen-unicode-properties.mjs`; `pnpm
 * install` does. The output is git-ignored, never committed.
 */
import { fileURLToPath } from "node:url";

import {
  UNICODE_VERSION,
  codePointsOf,
  spansOf,
  ucdSpans,
} from "./lib/ucd.mjs";
import { writeGenerated } from "./lib/write-generated.mjs";

const presentation = new Set(
  codePointsOf(await ucdSpans("Binary_Property/Emoji_Presentation")),
);

/** The range tables, by the export name each gets in the generated module.
 * @type {Readonly<Record<string, Array<[number, number]>>>} */
export const UNICODE_PROPERTIES = Object.freeze({
  EXTENDED_PICTOGRAPHIC: await ucdSpans(
    "Binary_Property/Extended_Pictographic",
  ),
  EMOJI_MODIFIER: await ucdSpans("Binary_Property/Emoji_Modifier"),
  EMOJI_TEXT_DEFAULT: spansOf(
    codePointsOf(await ucdSpans("Binary_Property/Emoji")).filter(
      (cp) => !presentation.has(cp),
    ),
  ),
  UNIFIED_IDEOGRAPH: await ucdSpans("Binary_Property/Unified_Ideograph"),
  SCRIPT_BRAILLE: await ucdSpans("Script/Braille"),
  SCRIPT_HANGUL: await ucdSpans("Script/Hangul"),
  GENERAL_CATEGORY_MARK: await ucdSpans("General_Category/Mark"),
});

/** @param {Array<[number, number]>} spans */
const rows = (spans) =>
  spans
    .map(
      ([start, end]) => `  [0x${start.toString(16)}, 0x${end.toString(16)}],`,
    )
    .join("\n");

/** Build the full source text of src/unicode-properties.mjs. */
export function renderUnicodeProperties() {
  const tables = Object.entries(UNICODE_PROPERTIES)
    .map(
      ([name, spans]) =>
        `/** @type {ReadonlyArray<readonly [number, number]>} */\nexport const ${name} = [\n${rows(spans)}\n];`,
    )
    .join("\n\n");
  return `/**
 * GENERATED by scripts/gen-unicode-properties.mjs from the pinned UCD ${UNICODE_VERSION} at
 * install time; git-ignored, never committed — DO NOT EDIT.
 *
 * The Unicode properties src/invisible.mjs's carve-out reads, PINNED so the
 * carve-out answers the same on every Node whatever its ICU's Unicode version.
 * Regenerate with \`node scripts/gen-unicode-properties.mjs\` (\`pnpm install\`
 * does).
 */

export const UNICODE_VERSION = ${JSON.stringify(UNICODE_VERSION)};

// GENERATED UCD data, not hand-written logic: each table is the sorted, merged
// [start, end] spans of one property. Pinned by the SSOT round-trip in
// test/unicode-properties.test.mjs, so Stryker skips the numeric literals.
// Stryker disable all
${tables}
// Stryker restore all

/**
 * True when \`cp\` lies in one of \`spans\` (sorted, non-overlapping). A negative
 * \`cp\` — the "no neighbour" sentinel — lies in none.
 * @param {ReadonlyArray<readonly [number, number]>} spans
 * @param {number} cp
 * @returns {boolean}
 */
export function inSpans(spans, cp) {
  let lo = 0;
  let hi = spans.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < spans[mid][0]) hi = mid - 1;
    else if (cp > spans[mid][1]) lo = mid + 1;
    else return true;
  }
  return false;
}
`;
}

export const MODULE_PATH = fileURLToPath(
  new URL("../src/unicode-properties.mjs", import.meta.url),
);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeGenerated(MODULE_PATH, renderUnicodeProperties());
  console.log(`wrote ${MODULE_PATH} (Unicode ${UNICODE_VERSION})`);
}
