#!/usr/bin/env node
/**
 * Generate the language-agnostic invisible-charset SSOT from invisible.mjs plus
 * the pinned UCD package (see ./lib/ucd.mjs).
 *
 * The authoritative definition of the payload-capable invisible characters lives
 * in `src/invisible.mjs` (the `VS` and `BLANK_NON_CF` exports) plus the Unicode
 * general-category `Cf`. A non-JS consumer — e.g. the Python `agent-secret-redactor`
 * engine — cannot import that module, and must NOT hand-copy the set: a fork is a
 * silent security regression (a code point added here but not there lets a key
 * spliced with it escape one layer).
 *
 * Resolving `Cf` LIVE in each consumer would read it from that runtime's own
 * Unicode database — Node (U17) and the CPython interpreter (often U14/U15)
 * ship DIFFERENT Unicode versions, so the two layers would strip DIFFERENT
 * `Cf` sets, and a key spliced with a code point in the version delta (e.g.
 * U+13439) would escape the layer on the older Unicode. `Cf` is instead
 * PINNED here at generation time (from the UCD package, not Node's `\p{Cf}`)
 * alongside the non-Cf extras, and every consumer reads the pinned list.
 * Version-locking the set is what makes the JS layer and the Python port strip
 * an identical set regardless of each runtime's own Unicode version.
 *
 * Writes `python/agent_sanitizer/data/invisible-charset.json` (packaged with
 * the Python client; read by `agent_sanitizer.invisible`). Its `cf_codepoints`
 * come from scripts/gen-cf-charset.mjs, the same pinned list `src/cf-charset.mjs`
 * carries for the JS layer, so the two cannot drift.
 * Run from the repo root: `node scripts/gen-invisible-charset.mjs`, AFTER
 * `gen-cf-charset.mjs` (this imports `src/invisible.mjs`, which imports the
 * module that one writes). `pnpm install` runs both in order
 * (scripts/gen-unicode.mjs); the JSON is git-ignored, never committed.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  CONTROL_INTRODUCER_CODEPOINTS,
  ESCAPE_SEQUENCE_SOURCE,
} from "../src/ansi.mjs";
import { VS, BLANK_NON_CF } from "../src/invisible.mjs";
import { cfCodepoints, unicodeVersion } from "./gen-cf-charset.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

/** Sorted, de-duped code points of every char in the given strings. */
export function extraCodepoints() {
  const cps = new Set();
  for (const s of [VS, BLANK_NON_CF])
    for (const ch of s) cps.add(ch.codePointAt(0));
  return [...cps].sort((a, b) => a - b);
}

export function charsetDoc() {
  return {
    _comment:
      "SSOT for the payload-capable invisible code points, generated by " +
      "scripts/gen-invisible-charset.mjs. `extra_codepoints` are the non-Cf extras " +
      "(variation selectors, blank-rendering fillers, zero-width combining marks) " +
      "from src/invisible.mjs (VS + BLANK_NON_CF). `cf_codepoints` is the general-" +
      "category Cf set PINNED from the UCD package at generation time (see " +
      "`unicode_version`) — NOT resolved live per consumer, because Node and CPython " +
      "ship different Unicode versions and a live-Cf split let a code point in the " +
      "version delta escape one layer. The deletion set is the UNION of the two " +
      "lists. `control_introducers` is the raw ANSI control-introducer set " +
      "(ESC + the C1 block) from src/ansi.mjs, which Layer 1 sweeps and the " +
      "Python textstrip port must sweep identically. `escape_sequence_pattern` " +
      "is the escape GRAMMAR from that same module, as a regex source valid in " +
      "JS and in Python `re` with no flags: src/ansi.mjs's scanner is the " +
      "authoritative implementation, and a stdlib-only consumer compiles this " +
      "rather than hand-writing a second spelling of it. Consumers in other " +
      "languages read this file instead of forking the lists — a fork is a " +
      "silent security regression.",
    unicode_version: unicodeVersion(),
    extra_codepoints: extraCodepoints(),
    cf_codepoints: cfCodepoints(),
    control_introducers: [...CONTROL_INTRODUCER_CODEPOINTS],
    escape_sequence_pattern: ESCAPE_SEQUENCE_SOURCE,
  };
}

export const OUTPUT_PATH = join(
  __dirname,
  "..",
  "python",
  "agent_sanitizer",
  "data",
  "invisible-charset.json",
);

function main() {
  // The JSON is the directory's only file and is git-ignored, so a fresh clone
  // has no python/agent_sanitizer/data/ to write into.
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, JSON.stringify(charsetDoc(), null, 2) + "\n");
  console.log(
    `wrote ${OUTPUT_PATH} (${extraCodepoints().length} extra + ${cfCodepoints().length} Cf code points)`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
