#!/usr/bin/env node
/**
 * Bundle the sanitizer CLI into a single self-contained `.mjs` for the Python
 * wheel.
 *
 * The Python client (`python/agent_sanitizer`) shells out to the Node
 * CLI. So `pip install` alone works — with only Node on PATH, no separate
 * JavaScript checkout and no `AGENT_SANITIZER_CLI` — this bundles
 * `bin/sanitize-cli.mjs` and everything it imports (the `src/` logic AND its npm
 * dependencies: remark/rehype/unified for the HTML layers) into ONE file with no
 * `node_modules` requirement, written into the Python package so the wheel ships
 * it.
 *
 * This is a BUILD ARTIFACT, generated at release time from `src/` at the current
 * version — not a hand-maintained port. There is exactly one source of truth
 * (`src/`) and one version per build, so it cannot drift the way a vendored copy
 * would. It is git-ignored and regenerated by the publish workflow; hatchling
 * force-includes it via `[tool.hatch.build] artifacts` (see python/pyproject.toml).
 *
 * The esbuild configuration and its two hardening passes live in
 * `scripts/lib/bundle-esbuild.mjs`, shared with the plugin build: a bare
 * `build({…})` here shipped a wheel whose `html: true` requests all failed,
 * because css-tree's runtime `require("../data/patch.json")` survived into the
 * artifact and the wheel has no such sibling file.
 *
 * Run from the repo root: `node scripts/bundle-python-cli.mjs`.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

import { bundleHardened, bundleTarget } from "./lib/bundle-esbuild.mjs";

// Straight-line: this file is only ever run as a script. bundleHardened throws
// on a bundle the wheel could not execute, so nothing is written in that case
// and the publish workflow stops instead of shipping it.
const target = bundleTarget("python-cli");
const text = await bundleHardened(target);
mkdirSync(dirname(target.outfile), { recursive: true });
writeFileSync(target.outfile, text);
process.stdout.write(`wrote ${target.outfile}\n`);
