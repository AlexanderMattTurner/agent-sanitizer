#!/usr/bin/env node
/**
 * Generate `src/cf-charset.mjs`: the general-category `Cf` code points, PINNED
 * from the UCD package (see ./lib/ucd.mjs) rather than asked of the runtime.
 *
 * Node (U17) and the CPython interpreter (often U14/U15) ship DIFFERENT Unicode
 * versions, so resolving `Cf` live in each layer would strip DIFFERENT sets and
 * a key spliced with a code point in the version delta (e.g. U+13439) would
 * escape the layer on the older Unicode. Every consumer reads this pinned list
 * instead: the JS layer through the module written here, the Python port through
 * `python/agent_sanitizer/data/invisible-charset.json`'s `cf_codepoints`
 * (scripts/gen-invisible-charset.mjs, which reads the SAME list from here).
 *
 * Split from gen-invisible-charset.mjs because that generator imports
 * `src/invisible.mjs`, which imports the module written HERE: with the output
 * untracked, one script producing both could not run on a fresh checkout.
 * Run from the repo root: `node scripts/gen-cf-charset.mjs`; `pnpm install`
 * does (scripts/gen-unicode.mjs). The output is git-ignored, never committed.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { UNICODE_VERSION, codePointsOf, ucdSpans } from "./lib/ucd.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

/** Every general-category `Cf` code point, sorted: the set both layers read. */
const CF_CODEPOINTS = codePointsOf(await ucdSpans("General_Category/Format"));
export function cfCodepoints() {
  return [...CF_CODEPOINTS];
}

/** The Unicode version the pinned `Cf` set was generated from. */
export function unicodeVersion() {
  return UNICODE_VERSION;
}

/** The generated `src/cf-charset.mjs` source: the pinned `Cf` set the JS layer
 * reads. A generated `src/` module (not a read of the Python-packaged JSON) so
 * it ships in the npm package, matching src/standardized-variants.mjs. */
export function cfCharsetModule() {
  const cps = cfCodepoints();
  // One code point per line, and the file is in .prettierignore. A flat number
  // array is the one shape Prettier repacks by `fill`, so any hand-chosen
  // wrapping loses a byte comparison against a fresh generation the moment the
  // set's width changes — which is what silently made this module drift from its
  // own generator. One per line also makes a new Cf code point a one-line diff.
  const hex = cps.map((cp) => `  0x${cp.toString(16)},`).join("\n");
  return `/**
 * GENERATED by scripts/gen-cf-charset.mjs from the pinned UCD
 * (General_Category=Cf, Unicode ${unicodeVersion()}) at install, pack and build
 * time; git-ignored, never committed — DO NOT EDIT.
 *
 * The general-category Cf code points, PINNED at generation time. invisible.mjs
 * strips exactly this set instead of asking the runtime for Cf, and the Python port
 * reads the SAME set from data/invisible-charset.json's \`cf_codepoints\`, so both
 * layers strip an identical Cf set regardless of each runtime's own Unicode
 * version. Regenerate with \`node scripts/gen-cf-charset.mjs\` (\`pnpm install\`
 * does).
 */

export const UNICODE_VERSION = "${unicodeVersion()}";

// GENERATED Unicode data, not hand-written logic. Its correctness is pinned by
// the SSOT round-trip in test/invisible-charset.test.mjs (re-derive the Cf set,
// then assert every code point matches) — Stryker skips the numeric literals.
// Stryker disable all
/** @type {readonly number[]} Sorted ascending. */
export const CF_CODEPOINTS = Object.freeze([
${hex}
]);
// Stryker restore all
`;
}

export const CF_MODULE_PATH = join(__dirname, "..", "src", "cf-charset.mjs");

function main() {
  writeFileSync(CF_MODULE_PATH, cfCharsetModule());
  console.log(
    `wrote ${CF_MODULE_PATH} (${cfCodepoints().length} Cf code points)`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
